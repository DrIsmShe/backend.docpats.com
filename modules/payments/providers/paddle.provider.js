// server/modules/payments/providers/paddle.provider.js
// ─────────────────────────────────────────────────────────────────────
//   Адаптер Paddle — merchant of record.
//   Включается, когда заданы:
//     PADDLE_API_KEY, PADDLE_WEBHOOK_SECRET, PADDLE_ENV (sandbox | production)
//
//   Пока это ЗАГЛУШКА, как iyzico и stripe.
//
//   Чем Paddle отличается от остальных провайдеров реестра — и почему
//   это не деталь реализации, а разное устройство сделки:
//
//   iyzico и Stripe — эквайеры: продавец вы, деньги ваши, НДС и налог с
//   продаж по каждой стране покупателя считаете и платите тоже вы.
//   Paddle — продавец записи (merchant of record): юридически врачу
//   продаёт подписку Paddle, а не DocPats. Налоги примерно в 200
//   юрисдикциях — его забота, вам приходит одна выплата за период.
//   Ради этого он и берётся при мировом масштабе: иначе бухгалтерия
//   растёт по стране на страну.
//
//   ЧЕГО PADDLE НЕ УМЕЕТ — важно помнить, прежде чем строить на нём
//   приём пациентов:
//
//     - платить третьим лицам. Схемы «пациент платит врачу, платформа
//       удерживает комиссию» на Paddle не существует в принципе, это не
//       вопрос настройки;
//     - политика допустимого использования запрещает «человеческие
//       услуги, не связанные с программным продуктом» и «продукты,
//       дающие медицинские советы». Приём у врача — ровно это.
//
//   Отсюда граница: Paddle пригоден ТОЛЬКО для подписок врачей и клиник
//   (это софт), и даже их надо согласовать с Paddle заранее — платформа
//   медицинская, трактовка на их стороне. Для оплаты приёмов нужен
//   Stripe Connect (врачи в США/Британии/ЕЭЗ/Канаде/Швейцарии) либо
//   локальный эквайер по региону.
// ─────────────────────────────────────────────────────────────────────

