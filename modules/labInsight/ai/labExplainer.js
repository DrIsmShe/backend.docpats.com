// ─────────────────────────────────────────────────────────────────────
//   Объяснение анализа человеческим языком — для ПАЦИЕНТА.
//
//   РАЗДЕЛЕНИЕ ТРУДА, на котором держится весь модуль:
//
//     labSheetReader  переписывает бланк      (модель, проверяемо глазом)
//     labFlags        считает отклонения      (арифметика, без модели)
//     labExplainer    объясняет, что это      (модель, вот этот файл)
//
//   Сюда модель получает УЖЕ ПОСЧИТАННЫЕ отклонения и не имеет права их
//   пересматривать. Она отвечает на вопрос «что такое гемоглобин и что
//   значит, что он ниже нормы» — то есть на вопрос из учебника, ответ на
//   который не зависит от конкретного пациента. Ровно поэтому её здесь
//   можно применять: ошибка стоит недоразумения, а не назначения.
//
//   ЧЕГО МОДЕЛЬ ЗДЕСЬ НЕ ДЕЛАЕТ И ПОЧЕМУ:
//
//   — не ставит диагноз. «Похоже на анемию» звучит как ответ, но им не
//     является: тот же гемоглобин бывает при десятке причин, и выбор
//     между ними — это осмотр, анамнез и другие анализы;
//   — не назначает и не отменяет лечение, не советует препараты и дозы,
//     в том числе безрецептурные. Человек, прочитавший «попейте железо»,
//     не пойдёт к врачу — а именно туда его и надо отправить;
//   — не успокаивает. «Ничего страшного» про чужой анализ — обещание,
//     которое давать не на чем;
//   — не пересчитывает и не оспаривает отклонения: числа уже посчитаны
//     программой, и расхождение между текстом и пометками на экране
//     разрушило бы доверие к обоим.
//
//   ЯЗЫК. Пятый–шестой класс: короткие фразы, без латыни и аббревиатур
//   без расшифровки. Человек читает это, волнуясь, — и текст, который
//   надо перечитывать, в таком состоянии не работает.
// ─────────────────────────────────────────────────────────────────────

import { EFFORT, runJson } from "../../diagnostics/ai/runner.js";

// Поднимать при КАЖДОМ изменении промпта: версия пишется в разбор.
export const PROMPT_VERSION = "labx-2026-08-17a";

const SCHEMA = {
  type: "object",
  additionalProperties: false,
  required: ["overview", "items", "seeDoctor"],
  properties: {
    overview: {
      type: "string",
      description:
        "2–3 предложения: что это за анализ и что в нём есть отклонения (или что все показатели в пределах нормы). Без диагнозов и без успокаивания.",
    },
    items: {
      type: "array",
      description:
        "По одному объяснению на КАЖДЫЙ показатель из входного списка, в том же порядке",
      items: {
        type: "object",
        additionalProperties: false,
        required: ["name", "whatItIs", "whatItMeans"],
        properties: {
          name: {
            type: "string",
            description: "Название показателя ровно как во входных данных",
          },
          whatItIs: {
            type: "string",
            description:
              "Одно предложение: что это за показатель и за что он отвечает в организме. Простыми словами.",
          },
          whatItMeans: {
            type: "string",
            description:
              "Одно-два предложения: что в общем случае означает такое отклонение и почему это стоит обсудить с врачом. Для показателей в норме — короткое «в пределах нормы». БЕЗ диагнозов, БЕЗ лечения.",
          },
        },
      },
    },
    seeDoctor: {
      type: "string",
      description:
        "Одно предложение о том, к какому специалисту и с какой срочностью имеет смысл обратиться. Без запугивания и без обесценивания.",
    },
  },
};

const SYSTEM = [
  "Ты объясняешь пациенту его анализ крови простыми словами.",
  "",
  "Отклонения УЖЕ посчитаны программой и переданы тебе. Твоя задача —",
  "объяснить, что означает каждый показатель. Пересматривать пометки",
  "«норма» и «отклонение» нельзя: экран покажет их рядом с твоим текстом,",
  "и расхождение человек воспримет как ошибку в обоих.",
  "",
  "КАТЕГОРИЧЕСКИ НЕЛЬЗЯ:",
  "— ставить диагноз или называть вероятную болезнь;",
  "— советовать лечение, препараты, дозы, БАДы, диеты — даже безрецептурные;",
  "— писать «ничего страшного», «всё в порядке», «не волнуйтесь»:",
  "  это обещание, которое дать не на чем;",
  "— пугать: «срочно», «опасно для жизни», «немедленно в больницу»;",
  "— упоминать конкретные заболевания даже как пример.",
  "",
  "НУЖНО:",
  "— писать так, как объяснил бы внимательный врач в разговоре;",
  "— короткие предложения, без латыни и без сокращений без расшифровки;",
  "— по каждому показателю: что это и что в общем случае значит такой сдвиг;",
  "— в конце — к какому врачу имеет смысл пойти с этим результатом.",
  "",
  "Человек читает это, волнуясь. Текст, который надо перечитывать,",
  "в таком состоянии не работает.",
].join("\n");

/** Как назвать уровень отклонения в тексте для модели. */
const LEVEL_WORD = {
  normal: "в пределах нормы",
  borderline: "у самой границы нормы",
  out: "за пределами нормы",
  far: "заметно за пределами нормы",
  unknown: "вывод сделать не на чем",
};

/**
 * Объяснить разобранный бланк.
 *
 * @param {object[]} evaluated — вывод labFlags.evaluateAll
 * @param {string} [language] — язык ответа
 */
export async function explainLab({ evaluated, language = "ru" }) {
  // Показатели, по которым вывода нет, В МОДЕЛЬ НЕ ИДУТ. Объяснять
  // значение, не зная нормы, — это домысливать норму, а именно этого мы
  // и избегаем. Экран покажет их отдельной строкой «нужен врач».
  const explainable = evaluated.filter((e) => e.level !== "unknown");

  if (!explainable.length) {
    return {
      overview:
        "На бланке не нашлось показателей с указанной нормой, поэтому " +
        "сравнить значения не с чем. Покажите результат врачу — он " +
        "оценит их по нормам вашей лаборатории.",
      items: [],
      seeDoctor:
        "Обратитесь к терапевту или к врачу, который назначил это исследование.",
      promptVersion: PROMPT_VERSION,
      model: null,
    };
  }

  const rows = explainable
    .map(
      (e) =>
        `${e.name}: ${e.rawValue}${e.unit ? " " + e.unit : ""} — ` +
        `${LEVEL_WORD[e.level]}` +
        (e.refText ? ` (норма по бланку: ${e.refText})` : ""),
    )
    .join("\n");

  const instruction = [
    `Язык ответа: ${language}.`,
    "",
    "Показатели с уже посчитанными пометками:",
    rows,
    "",
    "Дай объяснение по каждому из них в том же порядке.",
  ].join("\n");

  const { parsed, model } = await runJson({
    system: SYSTEM,
    schema: SCHEMA,
    what: "объяснение анализа",
    // Не рассуждение: пересказ учебника простыми словами.
    effort: EFFORT.extraction,
    // Потолок скромный намеренно: это должно читаться за минуту.
    maxTokens: 6000,
    instruction,
  });

  return {
    overview: String(parsed.overview || "").trim(),
    items: Array.isArray(parsed.items) ? parsed.items : [],
    seeDoctor: String(parsed.seeDoctor || "").trim(),
    model,
    promptVersion: PROMPT_VERSION,
  };
}

export default { explainLab, PROMPT_VERSION };
