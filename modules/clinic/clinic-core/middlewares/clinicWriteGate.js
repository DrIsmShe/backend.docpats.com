// server/modules/clinic/clinic-core/middlewares/clinicWriteGate.js
// ─────────────────────────────────────────────────────────────────────
//   Заморозка клиники, у которой кончился пробный период и нет оплаты.
//
//   ПОЧЕМУ ЗАМОРОЗКА, А НЕ ОТКЛЮЧЕНИЕ. В клинике лежат медицинские карты
//   пациентов. Закрыть к ним доступ из-за неоплаченного счёта — это не
//   коммерческое давление на клинику, а угроза для людей, которые к
//   счёту отношения не имеют: врач не увидит аллергию, регистратура не
//   найдёт направление. Коммерческая цель достигается запретом на НОВЫЕ
//   записи — работать клиника не может, а прошлое остаётся доступным и
//   выгружаемым.
//
//   ПОЧЕМУ ПО МЕТОДУ, А НЕ ПО СПИСКУ МАРШРУТОВ. Подмодулей около
//   двадцати, и список маршрутов устареет на первом же новом. Метод —
//   признак, который не устаревает: GET/HEAD/OPTIONS читают, остальное
//   пишет. Ошибка в сторону чтения безопасна.
//
//   ЧТО ОСТАЁТСЯ РАЗРЕШЁННЫМ ПРИ ЗАМОРОЗКЕ:
//     • всё чтение;
//     • выход сотрудника из системы — иначе человек заперт в интерфейсе,
//       из которого не может даже выйти.
//
//   Оплата идёт мимо этого роутера (/api/payments/*), поэтому разморозить
//   клинику заморозка не мешает.
// ─────────────────────────────────────────────────────────────────────

import { getCurrentClinicId } from "../../../../common/context/tenantContext.js";
import { resolveClinicAccess } from "../services/clinicPlan.service.js";

const READ_METHODS = new Set(["GET", "HEAD", "OPTIONS"]);

// Пути, которые обязаны работать даже у замороженной клиники. Сравнение
// по вхождению: роутеры смонтированы через router.use("/"), и req.path
// здесь — полный путь внутри /api/v1/clinic.
const ALWAYS_ALLOWED = ["/logout", "/employee/logout"];

export default async function clinicWriteGate(req, res, next) {
  try {
    if (READ_METHODS.has(req.method)) return next();
    if (ALWAYS_ALLOWED.some((p) => req.path.endsWith(p))) return next();

    const clinicId = getCurrentClinicId();
    // Контекста нет — значит клиника ещё не выбрана (создание клиники,
    // приём приглашения, вход сотрудника). Замораживать нечего.
    if (!clinicId) return next();

    const access = await resolveClinicAccess(clinicId);
    if (access.state !== "frozen") return next();

    return res.status(402).json({
      success: false,
      error: "CLINIC_SUBSCRIPTION_REQUIRED",
      message:
        "Пробный период клиники закончился. Данные и выгрузка доступны, " +
        "добавление новых записей — после оплаты тарифа.",
      trialEndedAt: access.until,
    });
  } catch (err) {
    // Сбой проверки не должен останавливать клинику: ошибиться в сторону
    // «пустить» здесь безопаснее, чем заблокировать приём из-за
    // недоступной базы.
    console.error("clinicWriteGate:", err.message);
    return next();
  }
}
