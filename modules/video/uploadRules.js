// Правила публикации роликов и версия, под которой человек подписался.
//
// ЗАЧЕМ ВЕРСИЯ. Согласие имеет смысл, только если известно, с чем именно
// согласились. Правила меняются; запись «принял 8 сентября» без указания
// редакции доказывает ровно ничего. Поэтому версия хранится вместе с
// отметкой в самой записи ролика.
//
// ЗАЧЕМ ПРАВИЛА ЖИВУТ НА СЕРВЕРЕ, А НЕ В ТЕКСТЕ СТРАНИЦЫ. Их читает и
// проверяет сервер (принята ли текущая редакция), а показывает клиент.
// Два списка в двух местах разъедутся при первой же правке.

/** Редакция правил. Меняется при любом изменении смысла, а не формулировок. */
export const ВЕРСИЯ_ПРАВИЛ = "2026-09-08";

/**
 * Что можно публиковать.
 *
 * Платформа медицинская, и тематика тут не вкусовщина: ролик про заработок
 * в интернете рядом с объяснением гастроскопии обесценивает второе.
 */
export const ТЕМЫ_РАЗРЕШЕНЫ = Object.freeze([
  "explainer_patient", // объяснение болезни, процедуры, подготовки — для пациента
  "education", // анатомия, физиология, разбор механизмов — для студентов и коллег
  "clinical_technique", // техника вмешательства, работа с оборудованием
  "research", // разбор исследований, доклад, конференция
  "clinic_info", // как записаться, как добраться, что взять с собой
  "doctor_intro", // визитка врача
]);

/**
 * Что публиковать нельзя.
 *
 * Список короткий намеренно: каждый пункт — то, из-за чего ролик снимут, а
 * не пожелание. Длинные своды правил не читают.
 */
export const ЗАПРЕЩЕНО = Object.freeze([
  "personal_data", // узнаваемый пациент, ФИО, дата рождения, номер карты — в кадре или в звуке
  "no_consent", // съёмка человека без его письменного согласия
  "drug_promo", // реклама препаратов и БАДов, продвижение бренда как лечения
  "unproven", // методы без доказательной базы, отказ от лечения, «народная медицина»
  "third_party", // чужие материалы без прав на использование
  "shock", // операционное поле и травмы без медицинской необходимости и предупреждения
  "diagnosis_public", // диагноз или назначение конкретному человеку публично
  "off_topic", // политика, религия, дискриминация, всё немедицинское
]);

/**
 * Требования к содержанию — то, что проверяет человек, а не программа.
 */
export const ТРЕБОВАНИЯ = Object.freeze([
  "accuracy", // соответствие действующим клиническим рекомендациям
  "sources", // указаны источники и лицензии использованных материалов
  "plain_language", // термины объясняются, если ролик для пациента
  "deidentified", // с кадров убраны имена, метки, номера исследований
]);

/**
 * Что признаёт загружающий.
 *
 * Формулировки нарочно от первого лица и без «настоящим уведомляю»: их
 * читает врач между приёмами, а не юрист.
 */
export const ОТВЕТСТВЕННОСТЬ = Object.freeze([
  "author_responsible", // за содержание, достоверность и права отвечает загрузивший
  "not_publisher", // платформа не издатель и не проверяет каждый ролик заранее
  "may_remove", // платформа вправе снять или архивировать ролик
  "not_a_consultation", // ролик не заменяет очную консультацию
  "data_processing", // файл хранится в защищённом хранилище и раздаётся по правилам видимости
]);

/**
 * Принята ли текущая редакция.
 *
 * Проверяем именно версию, а не факт галочки: подпись под прошлой редакцией
 * не означает согласия с новой.
 */
export function правилаПриняты(данные) {
  return (
    данные?.termsAccepted === true && данные?.termsVersion === ВЕРСИЯ_ПРАВИЛ
  );
}

export default {
  ВЕРСИЯ_ПРАВИЛ,
  ТЕМЫ_РАЗРЕШЕНЫ,
  ЗАПРЕЩЕНО,
  ТРЕБОВАНИЯ,
  ОТВЕТСТВЕННОСТЬ,
  правилаПриняты,
};
