// server/modules/video/render/scriptwriter.js
//
// Сценарий ролика из того, что уже лежит в базе.
//
// ЗАЧЕМ ЭТО ГЛАВНОЕ В ЗАТЕЕ. Библиотеки медицинских анимаций существуют
// давно и сняты лучше, чем сможем мы. Но у них ролик про «инфаркт вообще»,
// а здесь — про находки на конкретном снимке и про то, что сказали на
// конкретном приёме. Этого не купить: нужны данные, а они есть только у нас.
//
// ЧТО ДЕЛАЕТ МОДЕЛЬ И ЧЕГО НЕ ДЕЛАЕТ. Она перекладывает уже написанное
// врачом в разговорную речь и режет на сцены. Она не ставит диагнозов, не
// добавляет фактов и не даёт рекомендаций, которых нет в исходнике: ролик
// увидит пациент, и каждое лишнее утверждение в нём — это утверждение
// клиники, за которое отвечает врач.
//
// ПОЭТОМУ ЖЕ СЦЕНАРИЙ — ЧЕРНОВИК. Он идёт на рендер только после отметки
// врача (см. review в модели Video): текстовую неточность в статье можно
// поправить незаметно, а ролик, который пациент посмотрел перед операцией,
// уже нельзя.

import { runJson, isConfigured, str } from "../../radiology/ai/aiRunner.js";
import { ValidationError } from "../../../common/utils/errors.js";
import { VIDEO_LOCALES } from "../constants.js";

/** Сколько секунд на сцену. Ниже — мельтешение, выше — теряется внимание. */
const СЦЕНА_МИН = 4;
const СЦЕНА_МАКС = 20;

/** Предел длины ролика: объяснение, а не лекция. */
const РОЛИК_МАКС_СЕК = 180;

const СХЕМА = {
  type: "object",
  additionalProperties: false,
  required: ["title", "scenes"],
  properties: {
    title: { type: "string", maxLength: 120 },
    scenes: {
      type: "array",
      minItems: 2,
      maxItems: 12,
      items: {
        type: "object",
        additionalProperties: false,
        required: ["narration", "seconds"],
        properties: {
          // Текст диктора — то, что человек услышит.
          narration: { type: "string", maxLength: 600 },
          // Подпись на экране: короткая, читается за секунду.
          caption: { type: "string", maxLength: 120 },
          seconds: { type: "number", minimum: СЦЕНА_МИН, maximum: СЦЕНА_МАКС },
          // Что показать: ключ анатомической модели или кадр исследования.
          visual: { type: "string", maxLength: 200 },
        },
      },
    },
  },
};

const СИСТЕМА = [
  "Ты пишешь сценарий короткого разъяснительного ролика для пациента.",
  "Твоя работа — переложить готовый врачебный текст в спокойную устную речь,",
  "разбитую на сцены. Ты НЕ ставишь диагноз, НЕ назначаешь лечение и НЕ",
  "добавляешь фактов, которых нет в исходном тексте: всё, что скажет ролик,",
  "будет считаться словами клиники.",
  "",
  "Говори на «вы», без уменьшительных, без бодрого тона и без утешений вроде",
  "«не переживайте». Медицинский термин, если он важен, называй и тут же",
  "объясняй обычными словами. Если в исходнике чего-то нет — этого нет и в",
  "сценарии; не заполняй пробелы догадками.",
].join("\n");

/**
 * Сценарий по итогу консультации или приёма.
 *
 * @param {object} p
 * @param {string} p.summary      врачебный текст: эпикриз, итог консультации
 * @param {string} [p.procedure]  вмешательство, если ролик про подготовку
 * @param {string} [p.lang]       язык сценария
 */
export async function scriptFromSummary({ summary, procedure = "", lang = "ru" }) {
  const текст = str(summary, 8000);
  if (!текст) throw new ValidationError("Нет текста, из которого делать ролик");
  if (!VIDEO_LOCALES.includes(lang)) throw new ValidationError("Неизвестный язык");
  if (!isConfigured()) {
    throw new ValidationError("ИИ не настроен: сценарий собрать нечем");
  }

  const инструкция = [
    `Язык сценария: ${lang}.`,
    procedure ? `Ролик объясняет вмешательство: ${procedure}.` : "",
    "Исходный врачебный текст:",
    "---",
    текст,
    "---",
    `Общая длительность — не больше ${РОЛИК_МАКС_СЕК} секунд.`,
    "Первая сцена отвечает на вопрос «что у меня нашли», последняя — «что",
    "делать дальше», и только если это сказано в исходнике.",
  ]
    .filter(Boolean)
    .join("\n");

  const { parsed, usage } = await runJson({
    system: СИСТЕМА,
    instruction: инструкция,
    schema: СХЕМА,
    what: "сценарий ролика",
    maxTokens: 8000,
  });

  return собрать(parsed, usage, { kind: "consult_summary", lang });
}

/**
 * Сценарий разбора снимка.
 *
 * Здесь ценность максимальна и работа минимальна: находки уже размечены
 * врачом — есть ярлык, значимость и объяснение. Сценарий ведёт зрителя по
 * ним, а не сочиняет содержание.
 */
export async function scriptFromRadiologyCase({ caseDoc, lang = "ru" }) {
  if (!caseDoc) throw new ValidationError("Случай не найден");
  const находки = (caseDoc.findings || []).filter((н) => н.label);
  if (!находки.length) {
    throw new ValidationError("В случае нет размеченных находок — разбирать нечего");
  }
  if (!isConfigured()) {
    throw new ValidationError("ИИ не настроен: сценарий собрать нечем");
  }

  const список = находки
    .map(
      (н, i) =>
        `${i + 1}. ${н.label} (значимость: ${н.significance}). ${str(н.explanation, 800)}`,
    )
    .join("\n");

  const инструкция = [
    `Язык сценария: ${lang}.`,
    `Модальность исследования: ${caseDoc.modality || "не указана"}.`,
    "Размеченные врачом находки:",
    "---",
    список,
    "---",
    "Одна сцена — одна находка, в том же порядке. Объясняй только то, что",
    "написано в её пояснении. Заключение целиком не пересказывай.",
    `Общая длительность — не больше ${РОЛИК_МАКС_СЕК} секунд.`,
  ].join("\n");

  const { parsed, usage } = await runJson({
    system: СИСТЕМА,
    instruction: инструкция,
    schema: СХЕМА,
    what: "разбор снимка",
    maxTokens: 8000,
  });

  return собрать(parsed, usage, { kind: "radiology_review", lang });
}

/**
 * Привести ответ модели к сценарию.
 *
 * Длительность пересчитываем сами и обрезаем по потолку: модель охотно
 * отдаёт двенадцать сцен по двадцать секунд, а четырёхминутный ролик
 * «на две минуты» никто не досмотрит — и тогда рушится вся конструкция
 * согласия, которая держится на досмотре.
 */
function собрать(parsed, usage, { kind, lang }) {
  const scenes = [];
  let всего = 0;

  for (const сцена of parsed.scenes || []) {
    const сек = Math.min(Math.max(Number(сцена.seconds) || СЦЕНА_МИН, СЦЕНА_МИН), СЦЕНА_МАКС);
    if (всего + сек > РОЛИК_МАКС_СЕК) break;
    всего += сек;
    scenes.push({
      narration: str(сцена.narration, 600),
      caption: str(сцена.caption, 120),
      seconds: сек,
      visual: str(сцена.visual, 200),
    });
  }

  if (scenes.length < 2) {
    throw new ValidationError("Сценарий вышел слишком коротким — нужен пересмотр");
  }

  return {
    title: str(parsed.title, 120),
    kind,
    lang,
    scenes,
    durationSec: всего,
    usage: usage || null,
  };
}

export default { scriptFromSummary, scriptFromRadiologyCase };
