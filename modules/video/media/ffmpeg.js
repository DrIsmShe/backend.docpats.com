// server/modules/video/media/ffmpeg.js
//
// Работа с медиафайлом: длительность, звуковая дорожка, нарезка на HLS.
//
// ПОЧЕМУ ЭТОТ ФАЙЛ ПОЯВИЛСЯ. Без ffmpeg распознавание речи упиралось в
// чужой предел: Whisper принимает файл до 25 МБ, а ролик на десять минут
// весит сотни. Ролик почти целиком — это картинка; звук из него весит в
// десятки раз меньше и укладывается в предел с запасом. Тот же
// инструмент нужен и для HLS, и для честной длительности (сейчас её
// сообщает браузер, то есть тот, кто загружает).
//
// БИНАРНИК ЛЕЖИТ В ПРИЛОЖЕНИИ, А НЕ В СИСТЕМЕ. На сервере нет sudo, и
// статическая сборка в bin/ — единственный способ поставить ffmpeg, не
// прося администратора. Путь можно переопределить: на своей машине он
// обычно в PATH.
//
// ВСЁ ЗДЕСЬ — ВНЕШНИЙ ПРОЦЕСС, И У НЕГО ЕСТЬ СРОК. Ffmpeg на битом файле
// умеет висеть бесконечно; без таймаута это означало бы намертво занятый
// воркер.

import path from "node:path";
import os from "node:os";
import fs from "node:fs/promises";
import { spawn } from "node:child_process";
import { fileURLToPath } from "node:url";

const ЗДЕСЬ = path.dirname(fileURLToPath(import.meta.url));

/** Корень приложения: modules/video/media → server. */
const КОРЕНЬ = path.resolve(ЗДЕСЬ, "..", "..", "..");

function путьК(имя) {
  const свой = process.env[`${имя.toUpperCase()}_PATH`];
  if (свой) return свой;

  // Сборка рядом с приложением: она есть на сервере, где нет прав ставить
  // пакеты. Если её нет — надеемся на PATH (так работает разработка).
  return path.join(КОРЕНЬ, "bin", имя);
}

/** Есть ли на этой машине ffmpeg. Проверяем один раз за время жизни процесса. */
let доступен = null;

export async function ffmpegДоступен() {
  if (доступен !== null) return доступен;
  try {
    await запустить(путьК("ffmpeg"), ["-version"], { таймаут: 10000 });
    доступен = true;
  } catch {
    // Пробуем системный: на машине разработчика бинарника в bin/ нет.
    try {
      await запустить("ffmpeg", ["-version"], { таймаут: 10000 });
      доступен = true;
    } catch {
      доступен = false;
    }
  }
  return доступен;
}

/** Имя команды: своя сборка, если она есть, иначе системная. */
async function команда(имя) {
  try {
    await fs.access(путьК(имя));
    return путьК(имя);
  } catch {
    return имя;
  }
}

/**
 * Запустить процесс и дождаться его.
 *
 * Возвращает stdout. Ошибку собираем из stderr: ffmpeg пишет туда всё, и
 * без этого текста разбирать неудачу невозможно.
 */
function запустить(файл, аргументы, { таймаут = 300000 } = {}) {
  return new Promise((resolve, reject) => {
    const процесс = spawn(файл, аргументы, { windowsHide: true });

    let вывод = "";
    let ошибки = "";
    let убит = false;

    const часы = setTimeout(() => {
      убит = true;
      процесс.kill("SIGKILL");
    }, таймаут);

    процесс.stdout.on("data", (кусок) => {
      вывод += кусок.toString();
    });
    процесс.stderr.on("data", (кусок) => {
      // Держим только хвост: на длинном файле ffmpeg пишет мегабайты
      // прогресса, и хранить их целиком незачем.
      ошибки = (ошибки + кусок.toString()).slice(-4000);
    });

    процесс.on("error", (err) => {
      clearTimeout(часы);
      reject(err);
    });

    процесс.on("close", (код) => {
      clearTimeout(часы);
      if (убит) return reject(new Error("ffmpeg не уложился в отведённое время"));
      if (код !== 0) return reject(new Error(ошибки.trim() || `ffmpeg вышел с кодом ${код}`));
      resolve(вывод);
    });
  });
}

/** Временный файл в системном каталоге — с обязательной уборкой у вызывающего. */
export async function временныйФайл(расширение) {
  const каталог = await fs.mkdtemp(path.join(os.tmpdir(), "dp-video-"));
  return {
    путь: path.join(каталог, `f${расширение}`),
    убрать: () => fs.rm(каталог, { recursive: true, force: true }).catch(() => {}),
  };
}

/**
 * Длительность файла в секундах.
 *
 * До сих пор её сообщал браузер загружающего — то есть сторона, которой
 * верить нельзя: на длительности держатся квота рендера и порог досмотра
 * для видео-согласия.
 */
export async function длительность(путьФайла) {
  const вывод = await запустить(
    await команда("ffprobe"),
    [
      "-v",
      "error",
      "-show_entries",
      "format=duration",
      "-of",
      "default=noprint_wrappers=1:nokey=1",
      путьФайла,
    ],
    { таймаут: 60000 },
  );
  const сек = Number(String(вывод).trim());
  return Number.isFinite(сек) ? Math.round(сек) : 0;
}

/**
 * Вытащить звуковую дорожку в моно-MP3.
 *
 * ЗАЧЕМ ИМЕННО ТАК. Распознавателю не нужны ни стерео, ни высокая
 * частота: речь разборчива и в 16 кГц моно, а размер падает в десятки
 * раз — ролик на десять минут укладывается в предел 25 МБ вместо
 * нескольких сотен мегабайт видео.
 *
 * @returns {Promise<string>} путь к файлу; вызывающий обязан убрать каталог
 */
export async function извлечьЗвук(путьВидео, куда) {
  await запустить(
    await команда("ffmpeg"),
    [
      "-y",
      "-i",
      путьВидео,
      // Без видеодорожки — она здесь только мешает.
      "-vn",
      "-ac",
      "1",
      "-ar",
      "16000",
      "-b:a",
      "64k",
      куда,
    ],
    { таймаут: 600000 },
  );
  return куда;
}

/** Есть ли в файле звук вообще. Ролик без речи распознавать незачем. */
export async function естьЗвук(путьФайла) {
  try {
    const вывод = await запустить(
      await команда("ffprobe"),
      [
        "-v",
        "error",
        "-select_streams",
        "a",
        "-show_entries",
        "stream=codec_type",
        "-of",
        "csv=p=0",
        путьФайла,
      ],
      { таймаут: 60000 },
    );
    return String(вывод).includes("audio");
  } catch {
    // Не смогли спросить — считаем, что звук есть: пусть решает
    // распознаватель, а не догадка.
    return true;
  }
}

export default {
  ffmpegДоступен,
  длительность,
  извлечьЗвук,
  естьЗвук,
  временныйФайл,
};
