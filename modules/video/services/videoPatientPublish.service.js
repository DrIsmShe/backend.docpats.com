// Публикация ролика пациентом: одна полка и счётное число.
//
// ЗАЧЕМ ОТДЕЛЬНЫЕ ПРАВИЛА. Врач публикует объяснение по своей
// специальности — это его работа, и отвечает он за неё именем. Пациент
// рассказывает свою историю: это ценно, но лежит рядом с медицинскими
// разборами и путается с ними, если не отделить. Отсюда две вещи —
// своя полка и обозримое количество.
//
// ПОЛКА ОДНА, И ОНА НАЗНАЧАЕТСЯ СЕРВЕРОМ. Не потому, что пациенту нельзя
// доверять выбор, а потому, что «Разборы снимков» от пациента — это не
// разбор снимка. Раздел говорит читателю, чего ждать от ролика, и
// подменять это нельзя даже из лучших побуждений.
//
// СЧЁТ — НА ОПУБЛИКОВАННЫЕ, НЕ НА ЗАГРУЖЕННЫЕ. Снимать, хранить и
// показывать своему врачу пациент может в пределах места на тарифе.
// Ограничен только выход в общий каталог: его просматривает человек, и
// поток должен оставаться обозримым. Сняв ролик с витрины, пациент
// освобождает место для следующего.
//
// ГЛАВНОЕ ПРЕДУПРЕЖДЕНИЕ ЖИВЁТ В ИНТЕРФЕЙСЕ. Публикуя своё медицинское
// видео, человек раскрывает сведения о собственном здоровье — навсегда и
// всем. Это его право, но он должен понимать, что делает; отговаривать
// его сервер не вправе, а промолчать — не должен.

import Video from "../models/video.model.js";
import VideoCategory from "../models/videoCategory.model.js";
import { ValidationError, QuotaExceededError } from "../../../common/utils/errors.js";
import { getVideraPublicVideos } from "../../../common/config/aiPlanLimits.js";

/** Ключ полки пациентов. Одна на всех: см. комментарий выше. */
export const ПОЛКА_ПАЦИЕНТОВ = "patient-opinions";

/** Как полка называлась раньше — чтобы переименовать, а не завести вторую. */
const ПРЕЖНИЙ_КЛЮЧ = "patient-stories";

/** Название полки на пяти языках — на случай, если её ещё нет. */
const НАЗВАНИЕ = {
  ru: "Мнения пациентов",
  en: "Patient opinions",
  az: "Pasiyent rəyləri",
  tr: "Hasta görüşleri",
  ar: "آراء المرضى",
};

/**
 * Найти полку пациентов, создав её при первой надобности.
 *
 * Заводим сами, а не требуем от администратора: правило «пациент
 * публикует сюда» бессмысленно, если «сюда» может не существовать.
 */
export async function полкаПациентов() {
  const есть = await VideoCategory.findOne({ slug: ПОЛКА_ПАЦИЕНТОВ });
  if (есть) return есть;

  // Полка могла завестись под прежним именем — переименовываем, а не
  // заводим вторую: ролики, уже лежащие на ней, должны остаться на месте.
  const прежняя = await VideoCategory.findOne({ slug: ПРЕЖНИЙ_КЛЮЧ });
  if (прежняя) {
    прежняя.slug = ПОЛКА_ПАЦИЕНТОВ;
    прежняя.title = НАЗВАНИЕ;
    await прежняя.save();
    return прежняя;
  }

  return VideoCategory.create({
    slug: ПОЛКА_ПАЦИЕНТОВ,
    title: НАЗВАНИЕ,
    // В конце списка: витрина открывается медицинским содержимым, а
    // истории — рядом, но не вместо него.
    order: 900,
    active: true,
  });
}

/** Пациент ли это. Роль клиники (врач, сотрудник) сюда не попадает. */
export function этоПациент(user) {
  return user?.role === "patient";
}

/**
 * Проверить право пациента опубликовать ещё один ролик.
 *
 * @returns {Promise<{limit: number, used: number, left: number}>}
 * @throws {QuotaExceededError} когда полка заполнена
 */
export async function проверитьЛимитПубликаций({ user, ownerId, exceptId = null }) {
  const план = user?.subscriptionPlan || user?.subscription?.plan || "patient_free";
  const limit = getVideraPublicVideos(план);

  // -1 — без счёта: врачей и клиники ограничивают место и минуты.
  if (limit === -1) return { limit, used: 0, left: -1 };

  const условие = {
    ownerType: "user",
    ownerId,
    visibility: "public",
    archivedAt: null,
  };
  if (exceptId) условие._id = { $ne: exceptId };

  const used = await Video.countDocuments(условие);

  if (used >= limit) {
    throw new QuotaExceededError(
      limit === 0
        ? "На этом тарифе публикация в каталоге недоступна"
        : `Опубликовано ${used} из ${limit}. Снимите с витрины лишний ролик или смените тариф`,
    );
  }

  return { limit, used, left: limit - used };
}

/**
 * Что должно произойти с роликом пациента перед публикацией.
 *
 * Возвращает поля, которые вызывающий обязан применить: полку и признак
 * вида. Ничего не сохраняет сам — публикация остаётся одной операцией с
 * одним местом записи.
 */
export async function подготовитьПубликациюПациента(video) {
  const полка = await полкаПациентов();

  return {
    categoryId: полка._id,
    // Вид тоже свой: «объяснение» пишет врач, а это рассказ.
    kind: "other",
  };
}

export default {
  ПОЛКА_ПАЦИЕНТОВ,
  полкаПациентов,
  этоПациент,
  проверитьЛимитПубликаций,
  подготовитьПубликациюПациента,
};
