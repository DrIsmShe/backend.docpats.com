// server/modules/video/constants.js
//
// Словари каталога видео. Вынесены отдельно, потому что их читают и модель,
// и валидаторы, и тесты: держать их в модели значило бы тянуть mongoose туда,
// где нужен один массив строк.

/**
 * ВИД РОЛИКА — зачем он снят. От вида зависит, где ролик показывается и
 * можно ли его вообще выпускать наружу.
 */
export const VIDEO_KINDS = Object.freeze([
  "explainer", // объяснение болезни/вмешательства — основной вид
  "consult_summary", // итог консультации для конкретного человека
  "radiology_review", // разбор снимка
  "encounter_record", // запись приёма (всегда PHI)
  "promo", // визитка врача, ролик клиники
  "other",
]);

/**
 * ОТКУДА ВЗЯЛСЯ ФАЙЛ. Разделено с видом намеренно: объяснительный ролик
 * можно и снять в студии, и собрать из эпикриза машиной, а спрашивают потом
 * разное — «про что фильм» и «кто его сделал».
 */
export const VIDEO_SOURCES = Object.freeze([
  "studio", // человек снял в DP-Videra
  "generated", // собран из данных платформы (фаза 3)
  "upload", // загружен файлом
  "call_record", // запись видеозвонка (фаза 2)
]);

/**
 * ВИДИМОСТЬ. Порядок — от узкого к широкому, и это не просто список:
 * `private` обязан оставаться значением по умолчанию. Ролик, снятый в
 * кабинете врача, не должен оказаться на витрине из-за незаполненного поля.
 *
 *   private — только владелец
 *   clinic  — любой член клиники, к которой привязан ролик
 *   link    — кто знает адрес; в списки и выдачу не попадает
 *   public  — витрина DP-TUBE, sitemap, соцсети
 */
export const VIDEO_VISIBILITY = Object.freeze([
  "private",
  "clinic",
  "link",
  "public",
]);

/**
 * СОСТОЯНИЕ ФАЙЛА.
 *
 *   draft      — запись есть, файла ещё нет (сняли заявку, ждём студию)
 *   processing — студия рендерит
 *   ready      — файл на месте, можно смотреть
 *   failed     — рендер не удался; причина в failureReason
 */
export const VIDEO_STATUSES = Object.freeze([
  "draft",
  "processing",
  "ready",
  "failed",
]);

/**
 * ЯЗЫКИ. Те же пять, что и во всём приложении.
 */
export const VIDEO_LOCALES = Object.freeze(["ru", "en", "az", "tr", "ar"]);

/**
 * ЛИЦЕНЗИИ исходных материалов. Список закрытый, и это осознанно: «SA»
 * заражает производное — ролик, где использована модель под CC BY-SA,
 * обязан выйти под той же лицензией и не может стать закрытым платным
 * контентом. Хранить лицензию свободной строкой значит однажды не суметь
 * ответить на вопрос «что из этого можно продавать».
 */
export const VIDEO_LICENSES = Object.freeze([
  "CC0",
  "CC-BY-4.0",
  "CC-BY-SA-4.0",
  "CC-BY-NC-4.0",
  "proprietary", // собственная съёмка или купленный материал
]);

/** Лицензии, которые заражают производное: ролик обязан выйти под той же. */
export const SHARE_ALIKE_LICENSES = Object.freeze(["CC-BY-SA-4.0"]);

export default {
  VIDEO_KINDS,
  VIDEO_SOURCES,
  VIDEO_VISIBILITY,
  VIDEO_STATUSES,
  VIDEO_LOCALES,
  VIDEO_LICENSES,
  SHARE_ALIKE_LICENSES,
};
