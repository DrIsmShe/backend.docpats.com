// server/modules/radiology/reading-systems/base.js
//
// Форма «системы чтения» и её умолчания. Система чтения — это ПЛАГИН на
// одну модальность: он описывает, чем читают такое исследование и как его
// оценивают. Ядро (модели, попытки, скоринг) одно на всех; различия между
// КТ, МРТ и УЗИ вынесены сюда — ровно смысл «одна система на одно
// исследование».
//
// Плагин задаёт пять вещей:
//   viewer    — что умеет просмотрщик (окна, листание срезов, инструменты);
//   checklist — протокол систематического осмотра (то, что учит «читать
//               по порядку, ничего не пропуская»);
//   scoring   — веса компонентов оценки, порог, радиус совпадения находок;
//   а также человекочитаемые title/description для UI.
//
// Словарь находок (палитра) не дублируется в плагине: он выводится из
// lexicon.js по модальности кейса.

// Веса компонентов оценки. Сумма НЕ обязана быть равна 1: скоринг
// перенормирует по фактически применённым компонентам (например, если
// ИИ-грейдинг заключения выключен, его вес исключается, а не штрафует).
export const DEFAULT_SCORING = {
  weights: {
    detection: 0.35, // нашёл ли находки там, где они есть
    classification: 0.15, // верно ли назвал найденное
    checklist: 0.15, // прошёл ли протокол осмотра целиком
    diagnosis: 0.25, // верный ли итоговый диагноз
    aiImpression: 0.1, // качество свободного заключения (ИИ/эвристика)
  },
  // Радиус совпадения разметки учащегося с эталоном, доля от размера кадра.
  // 0.1 ≈ «попал примерно в ту же зону»; localization, не пиксель-в-пиксель.
  matchRadius: 0.1,
  // Штраф за ложную тревогу (находка там, где её нет), в единицах веса
  // значимости. 1 ≈ «ложный critical стоит как пропущенный incidental».
  falseAlarmPenalty: 1,
  // Проходной балл.
  passThreshold: 0.7,
};

export const DEFAULT_VIEWER = {
  multiSlice: false, // стек срезов или один кадр
  tools: ["zoom", "pan", "measure", "roi"],
  windowPresets: [], // пресеты окна, если применимы (КТ)
};

/**
 * Достраивает плагин умолчаниями. Плагин переопределяет только то, что у
 * него отличается, — остальное берётся из DEFAULT_*.
 */
export function defineReadingSystem(spec) {
  return {
    modality: spec.modality,
    title: spec.title,
    description: spec.description ?? "",
    viewer: { ...DEFAULT_VIEWER, ...(spec.viewer ?? {}) },
    checklist: spec.checklist ?? [],
    scoring: {
      ...DEFAULT_SCORING,
      ...(spec.scoring ?? {}),
      weights: { ...DEFAULT_SCORING.weights, ...(spec.scoring?.weights ?? {}) },
    },
  };
}
