// СОСТОЯНИЕ ПРОГОНА АГЕНТА, хранимое в самом кейсе.
//
// Зачем оно вообще. Агент делает до пятнадцати последовательных вызовов Opus
// с рассуждением: цикл «правка → перепроверка», разбор судьёй, точечные
// правки, перевод после публикации. В один HTTP-запрос это не влезает ни при
// каком таймауте — nginx рвёт соединение на 240 с, а узел спокойно
// досчитывает и публикует кейс, о котором врачу уже сказали «Network Error».
// Мы это чинили дважды и оба раза лечили симптом; лечится оно одним —
// прогон не должен жить внутри запроса.
//
// ПОЧЕМУ В КЕЙСЕ, А НЕ ОТДЕЛЬНОЙ КОЛЛЕКЦИЕЙ. Прогон принадлежит ровно одному
// кейсу, интересен только пока идёт, и читается вместе с ним. Отдельная
// коллекция означала бы новую модель, новые маршруты и новый опрос — при том
// что клиент УЖЕ перечитывает кейс после прогона. Так опрос сводится к тому
// же самому GET, который админка и так умеет.
//
// ПОЧЕМУ БЕЗ ОЧЕРЕДИ. У переводов очередь есть (BullMQ), и там она нужна:
// сотни статей, ретраи, воркер. Агента запускает человек, глядя на экран,
// по одному кейсу за раз. Очередь добавила бы Redis в путь, который прекрасно
// живёт без него, и отложила бы старт на неопределённое время — а человек
// ждёт ответа здесь и сейчас.
//
// ЧЕГО ЭТО НЕ РЕШАЕТ. Перезапуск процесса посреди прогона оставит запись в
// состоянии "running" навсегда: фоновая работа живёт в памяти узла и рестарт
// её не переживает. Поэтому у записи есть startedAt, а клиент считает
// протухшим прогон, который идёт дольше разумного, — иначе кнопка осталась бы
// заблокированной до ручного вмешательства.

import mongoose from "mongoose";

const { Schema } = mongoose;

export function agentRunField() {
  return {
    agentRun: {
      // idle — прогонов не было; running — идёт; done — закончился;
      // failed — упал с ошибкой, которую видел вызывающий.
      status: {
        type: String,
        enum: ["idle", "running", "done", "failed"],
        default: "idle",
      },
      startedAt: { type: Date, default: null },
      finishedAt: { type: Date, default: null },
      // Отчёт runCaseAgent целиком, как его получал бы синхронный вызов.
      // Schema.Types.Mixed намеренно: форма отчёта — это контракт агента с
      // админкой, и дублировать её схемой значит завести второе место,
      // которое разойдётся с первым на ближайшей правке.
      report: { type: Schema.Types.Mixed, default: null },
      error: { type: String, default: null },
      // Кто запустил. У ночного прогона — null.
      actorId: { type: Schema.Types.ObjectId, ref: "User", default: null },
    },
  };
}
