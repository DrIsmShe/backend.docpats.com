// ЧЕТВЁРТЫЙ ПРОХОД: РАЗБОР ЗАСТРЯВШИХ ЗАМЕЧАНИЙ.
//
// Цикл «правка → перепроверка» (ai/autoFix.js) останавливается, когда число
// замечаний перестаёт падать. Это правильная остановка — дальше редактор и
// рецензент топчутся, — но она оставляет кейс в подвешенном состоянии: гейт
// считает ЛЮБОЕ неразобранное замечание, и агент, которому запрещено их
// закрывать, не мог опубликовать ничего, где рецензент упёрся хоть в одну
// строку. На практике это значило, что «Запустить агента» почти всегда
// заканчивался словами «осталось сделать вам».
//
// Этот проход отвечает на один вопрос по каждому застрявшему замечанию:
// ОНО ВООБЩЕ ВЕРНОЕ? Свежим вызовом, который не видит ни рассуждений
// рецензента, ни рассуждений редактора — только текст кейса и текст
// замечания. Обоснованные уходят на точечную правку, необоснованные
// закрываются с письменным обоснованием, и обоснование остаётся в кейсе
// (aiReview.agentResolved) — чтобы человек, открывший кейс через неделю,
// видел не «замечаний нет», а «замечание было, машина сочла его неверным,
// вот почему».
//
// ПОЧЕМУ ЭТО НЕ «ОБМАН ГЕЙТА». Гейт требует, чтобы каждое замечание было
// ПРОЧИТАНО и по нему принято решение. Раньше единственным читателем мог
// быть человек, потому что машине нечем было отчитаться. Теперь есть:
// решение по каждому замечанию именное, письменное и хранится в кейсе.
// Разница с человеком остаётся, и она честная — судья та же модель, что
// писала и рецензировала кейс, поэтому общее для всех трёх ролей
// заблуждение переживает и этот проход. Отчёт агента говорит об этом прямо,
// а закрытые машиной замечания показываются отдельным списком, и человек
// может вернуть любое обратно.
//
// ЧЕГО СУДЬЯ НЕ ДЕЛАЕТ: не правит кейс (правит редактор) и не выносит
// вердикт «кейс верен» — он высказывается только о конкретных замечаниях.

import { ValidationError } from "../../../common/utils/errors.js";
import { runJson, isConfigured, str } from "./aiRunner.js";

export { isConfigured };

const SYSTEM = `Ты — врач-эксперт и третейский судья в споре двух других экспертов об учебном медицинском кейсе.

Один эксперт написал кейс, второй его отрецензировал. Спор зашёл в тупик: редактор правил кейс по замечаниям, но рецензент продолжает возражать. Тебе дан текущий текст кейса и оставшиеся замечания. По КАЖДОМУ замечанию реши: оно обоснованно или нет.

Что значит ОБОСНОВАННО (founded = true):
- замечание указывает на фактическую ошибку в кейсе: неверный референсный интервал, невозможное сочетание данных, противоречие между показателями и заключением, неверный диагноз или стадия;
- либо на то, что делает кейс непригодным как учебная задача: ответ подписан прямо в условии, у задачи нет однозначного решения, эталон не следует из данных.

Что значит НЕОБОСНОВАННО (founded = false):
- утверждение рецензента неверно фактически — проверь по тексту кейса сам, а не верь на слово;
- рецензент требует того, чего кейс не обязан содержать: дополнительных показателей, серий, анамнеза, оговорок. Учебный кейс намеренно ограничен, и «мало данных» — не ошибка, если из имеющихся ответ выводится однозначно;
- рецензент спорит о стиле, формулировке или полноте, а не о факте;
- замечание уже учтено в текущем тексте, а рецензент этого не заметил.

Проверяй по ТЕКУЩЕМУ тексту кейса, который тебе дан, а не по тому, каким кейс мог быть раньше.

Не поддавайся ни одной стороне из вежливости. Ошибка в обе стороны стоит по-разному: пропустить настоящую ошибку хуже, чем оставить лишнее замечание человеку. Если сомневаешься — обоснованно.

why пиши для человека, который увидит это в кейсе и должен понять твоё решение без перечитывания спора: одно-два предложения, по существу, без «как указано выше».`;

const SCHEMA = {
  type: "object",
  additionalProperties: false,
  required: ["verdicts"],
  properties: {
    verdicts: {
      type: "array",
      description:
        "По одной записи на КАЖДОЕ замечание из списка, в том же порядке. Ни одно не пропускай.",
      items: {
        type: "object",
        additionalProperties: false,
        required: ["number", "founded", "why"],
        properties: {
          number: {
            type: "integer",
            description: "Номер замечания из списка, начиная с 1.",
          },
          founded: {
            type: "boolean",
            description:
              "true — замечание верное, кейс надо править. false — замечание неверное или не по делу.",
          },
          why: {
            type: "string",
            description:
              "Обоснование решения, одно-два предложения. Это увидит врач в карточке кейса.",
          },
        },
      },
    },
  },
};

function issuesText(issues) {
  const rows = issues
    .map((i, n) => {
      const head = `${n + 1}. [${i.severity === "error" ? "ошибка" : "внимание"}]${
        i.target ? ` ${i.target}:` : ""
      }`;
      const body = str(i.issue, 1500);
      const fix = str(i.suggestion, 1500);
      return `${head} ${body}${fix ? `\n   Предложение рецензента: ${fix}` : ""}`;
    });
  return rows.join("\n");
}

/**
 * Разобрать застрявшие замечания.
 *
 * @param {object}   args
 * @param {object}   args.draft   текущий текст кейса (тот же вид, что уходит редактору)
 * @param {object[]} args.issues  оставшиеся замечания рецензента
 * @param {string}   [args.station] подпись станции для промпта
 * @returns {Promise<{
 *   verdicts: Array<{index: number, founded: boolean, why: string}>,
 *   usage: {inputTokens: number, outputTokens: number},
 *   model: string
 * }>} verdicts в том же порядке и той же длины, что issues
 */
export async function adjudicateIssues({ draft, issues, station = "" }) {
  const list = (Array.isArray(issues) ? issues : []).filter((i) =>
    str(i?.issue, 1500),
  );
  if (!list.length) throw new ValidationError("Нет замечаний для разбора");

  const { parsed, usage, model } = await runJson({
    system: SYSTEM,
    instruction: `${station ? `Станция: ${station}.\n\n` : ""}Текущий текст кейса:\n\n${JSON.stringify(
      draft,
      null,
      2,
    ).slice(0, 60000)}\n\nОставшиеся замечания рецензента:\n${issuesText(
      list,
    )}\n\nВынеси решение по каждому из ${list.length} замечаний.`,
    schema: SCHEMA,
    what: "разбор замечаний",
  });

  // Модель может пропустить замечание или прислать номер вне диапазона.
  // Умолчание для непокрытых — «обоснованно»: молчание судьи не должно
  // открывать гейт, иначе оборванный ответ публиковал бы кейс.
  const byIndex = new Map();
  for (const v of Array.isArray(parsed.verdicts) ? parsed.verdicts : []) {
    const index = Number(v?.number) - 1;
    if (!Number.isInteger(index) || index < 0 || index >= list.length) continue;
    if (byIndex.has(index)) continue;
    byIndex.set(index, {
      index,
      founded: Boolean(v.founded),
      why: str(v.why, 1200),
    });
  }

  const verdicts = list.map(
    (_, index) =>
      byIndex.get(index) ?? {
        index,
        founded: true,
        why: "Судья не высказался по этому замечанию — оставлено человеку.",
      },
  );

  // Решение «необоснованно» без обоснования не принимаем: именно обоснование
  // делает закрытие замечания машиной проверяемым, а без него это молчаливое
  // «пропустить».
  for (const v of verdicts) {
    if (!v.founded && !v.why) {
      v.founded = true;
      v.why = "Судья не обосновал отклонение замечания — оставлено человеку.";
    }
  }

  return { verdicts, usage, model };
}

export default adjudicateIssues;
