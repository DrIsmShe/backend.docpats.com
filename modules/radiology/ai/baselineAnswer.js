// server/modules/radiology/ai/baselineAnswer.js
//
// «Типовой ответ чат-бота» на кейс. Автор нажимает кнопку один раз, ответ
// сохраняется в кейсе (aiBaseline) и дальше служит образцом для сравнения:
// если заключение врача дословно повторяет этот текст длинными цепочками
// слов, это видно (integrity.service.js → verbatim_ai).
//
// Зачем именно образец, а не «детектор ИИ»: детекторов сгенерированного
// текста, которым можно верить, не существует, и обвинять человека на
// основании стиля нельзя. А вот совпадение пятисловных цепочек с конкретным
// сохранённым текстом — измеримый факт. Совпадение смысла тут ни при чём:
// правильные ответы естественно похожи, дословные — почти никогда.
//
// Важно: модель просят ответить ТАК, КАК ОТВЕТИЛ БЫ ОБЫЧНЫЙ ЧАТ-БОТ врачу,
// то есть без доступа к эталону автора. Поэтому в промпт уходит только то,
// что видит учащийся: жалоба, панель, контекст. Эталон не передаём —
// иначе получим пересказ эталона, а не то, что реально принесут из чата.

import { runJson, str, isConfigured } from "./aiRunner.js";

export { isConfigured };

const SCHEMA = {
  type: "object",
  additionalProperties: false,
  required: ["answer"],
  properties: {
    answer: {
      type: "string",
      description:
        "Ответ на задачу так, как его дал бы обычный чат-бот врачу: заключение и наиболее вероятный диагноз, обычным для таких ответов языком и структурой.",
    },
  },
};

const SYSTEM = [
  "Ты имитируешь ответ универсального чат-бота на медицинскую учебную задачу.",
  "Отвечай так, как отвечают такие ассистенты: связный текст, типовая структура,",
  "уверенный тон, ключевые термины полностью. Не задавай вопросов, не проси уточнений,",
  "не упоминай, что ты имитация. Пиши по-русски.",
].join(" ");

/**
 * @param {object} a
 * @param {string} a.title
 * @param {string} [a.context]  клинический контекст/жалоба, как видит учащийся
 * @param {string[]} [a.data]   строки данных (панель анализов, результаты)
 * @param {string} a.station    radiology | labs | vp — только для формулировки
 * @returns {Promise<{text: string, model: string}>}
 */
export async function generateBaselineAnswer({ title, context = "", data = [], station = "labs" }) {
  const what =
    station === "vp"
      ? "клинический сценарий"
      : station === "radiology"
        ? "описание случая по снимку"
        : "набор лабораторных данных";

  const instruction = [
    `Задача (${what}): ${str(title, 300)}`,
    context ? `Клинические данные: ${str(context, 3000)}` : null,
    data.length ? `Показатели и результаты:\n${data.map((d) => `- ${str(d, 200)}`).join("\n")}` : null,
    "",
    "Дай ответ: интерпретация и наиболее вероятный диагноз.",
  ]
    .filter(Boolean)
    .join("\n");

  const { parsed, model } = await runJson({
    system: SYSTEM,
    instruction,
    schema: SCHEMA,
    maxTokens: 4000,
    what: "типовой ответ",
  });

  // model — та, что реально ответила (при fallbacks это не запрошенная).
  return { text: str(parsed.answer, 6000), model };
}
