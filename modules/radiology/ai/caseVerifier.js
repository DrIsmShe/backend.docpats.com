//
// ВТОРОЙ ПРОХОД: проверка сгенерированного кейса свежим контекстом.
//
// Зачем отдельный вызов, а не «проверь себя» в промпте генератора: модель
// уровня Opus 5 и без указаний перепроверяет свою работу, а явная инструкция
// на самопроверку даёт лишнюю возню без прироста точности. Работает другое —
// отдельный вызов, который НЕ видит рассуждений первого прохода и потому не
// привязан к ним. Ошибки от этого не становятся независимыми (модель та же,
// блайндспоты общие), поэтому реальный выигрыш здесь — на внутренней
// противоречивости данных, а не на общем факте:
//
//   ловит хорошо — ферритин ↓ при ОЖСС ↓, «микроцитарная» при MCV 95,
//                  флаг «значимо» на нормальном показателе, лишнее
//                  обследование в «нужных», диагноз без опоры на данные;
//   ловит плохо  — правдоподобный, но неверный референсный интервал,
//                  который оба прохода считают правильным.
//
// Верификатор НИЧЕГО НЕ ПРАВИТ. Он возвращает замечания с привязкой к
// конкретному показателю/обследованию — иначе получился бы второй слой
// выдумывания без следов. Решение принимает автор-человек.

import { ISSUE_SEVERITIES } from "../constants.js";
import { ValidationError } from "../../../common/utils/errors.js";
import { runJson, isConfigured, str } from "./aiRunner.js";

export { isConfigured };

// Уровни. error — кейс в таком виде учит неверному (публиковать нельзя);
// warning — спорно или требует внимания эксперта.
// Серьёзность замечания живёт в constants.js: на неё ссылается схема кейса,
// а модель не должна зависеть от ИИ-модуля. Реэкспорт — для совместимости.
export { ISSUE_SEVERITIES };

const ISSUE_SCHEMA = {
  type: "object",
  additionalProperties: false,
  required: ["verdict", "issues", "summary"],
  properties: {
    verdict: {
      type: "string",
      enum: ["clean", "issues"],
      description: "clean — замечаний нет; issues — есть что поправить.",
    },
    issues: {
      type: "array",
      description:
        "Замечания. Пустой массив, если кейс согласован. Не придумывай замечания ради их наличия: ложная тревога стоит эксперту времени.",
      items: {
        type: "object",
        additionalProperties: false,
        required: ["target", "severity", "issue", "suggestion"],
        properties: {
          target: {
            type: "string",
            description:
              "К чему замечание: точное название показателя или обследования из кейса, либо одно из слов: impression, context, title, findings, case.",
          },
          severity: {
            type: "string",
            enum: ISSUE_SEVERITIES,
            description:
              "error — данные противоречивы или кейс учит неверному; warning — спорно, нужен взгляд эксперта.",
          },
          issue: {
            type: "string",
            description: "Что именно не так — конкретно, со ссылкой на цифры кейса.",
          },
          suggestion: {
            type: "string",
            description:
              "Как поправить: предложение для автора. Не переписывай кейс целиком.",
          },
        },
      },
    },
    summary: {
      type: "string",
      description: "Одно-два предложения: пригоден ли кейс и что главное поправить.",
    },
  },
};

// Общая часть системного промпта. Ключевое требование — не выдумывать
// замечания: верификатор, который «на всякий случай» помечает половину
// панели, обесценивает сам себя и приучает автора всё пролистывать.
const COMMON_RULES = `Ты — врач-эксперт, который РЕЦЕНЗИРУЕТ черновик учебного кейса перед публикацией в медицинском тренажёре. Кейс сгенерирован автоматически, ты видишь только результат — не рассуждения автора.

Что проверять:
1. СОГЛАСОВАННОСТЬ данных между собой: показатели/результаты не должны противоречить друг другу и клинической картине.
2. Единицы измерения и референсные интервалы: реальны ли они для взрослого пациента, соответствуют ли показателю.
3. Обоснованность разметки эталона (что помечено как значимое/нужное): помечено ли именно то, что клинически важно, и не помечено ли лишнее.
4. Диагноз: выводится ли он однозначно из приведённых данных; нет ли не менее вероятной альтернативы, которую данные не отвергают.
5. Пригодность как учебного материала: не учит ли кейс неверной эвристике.

Как выбирать severity (от этого зависит, заблокирует ли замечание публикацию — блокирует только error):
- error — данные противоречат друг другу или эталону; арифметика не сходится; заявленный диагноз не выводится из приведённых данных; кейс учит КЛИНИЧЕСКИ ОПАСНОМУ: противопоказанный препарат, неверная тактика при угрожающем состоянии, пропуск жизнеугрожающего состояния.
- warning — спорная трактовка, неполнота, неоднозначная формулировка, вопрос к эксперту.
- НЕ ЗАНИЖАЙ уровень: клинически опасная рекомендация — это error, даже если остальной кейс безупречен. Ошибка в дозе или противопоказании опаснее рассогласованной пометки.

Как отвечать:
- НИЧЕГО НЕ ПЕРЕПИСЫВАЙ. Только замечания и предложения.
- Не выдумывай замечаний. Если кейс согласован — верни verdict "clean" и пустой список. Ложная тревога стоит эксперту времени.
- Стилистику, формулировки и оформление не трогай — только содержание.
- target указывай ТОЧНЫМ названием показателя или обследования, как оно написано в кейсе.
- Пиши по-русски, по существу.

Ответ верни строго в заданной JSON-структуре.`;

// Нормализация: severity из перечисления, тексты обрезаны, пустые отброшены.
function normalize(parsed) {
  const issues = (Array.isArray(parsed.issues) ? parsed.issues : [])
    .map((i) => ({
      target: str(i?.target, 160),
      severity: ISSUE_SEVERITIES.includes(i?.severity) ? i.severity : "warning",
      issue: str(i?.issue, 1500),
      suggestion: str(i?.suggestion, 1500),
    }))
    .filter((i) => i.issue)
    .slice(0, 30);

  // verdict модели не доверяем вслепую: он должен соответствовать списку,
  // иначе UI покажет «замечаний нет» при непустом списке.
  return {
    verdict: issues.length ? "issues" : "clean",
    issues,
    errorCount: issues.filter((i) => i.severity === "error").length,
    summary: str(parsed.summary, 2000),
  };
}

// Кейс отдаём модели как JSON — без «эталон/черновик» обёрток, чтобы она
// оценивала данные, а не наши формулировки.
function asJson(value) {
  return JSON.stringify(value, null, 2).slice(0, 60000);
}

/**
 * Проверка кейса станции «Анализы».
 * @param {object} args.draft черновик (title, clinicalContext, panel, impression)
 */
export async function verifyLabCase({ draft }) {
  if (!draft || !Array.isArray(draft.panel)) {
    throw new ValidationError("Нет кейса для проверки");
  }

  const { parsed, usage } = await runJson({
    system: `${COMMON_RULES}

Кейс станции «Анализы»: учащийся видит клинический контекст и панель результатов, отмечает значимо отклонённые показатели и ставит диагноз. Поле significant — это эталон: показатель, который учащийся ОБЯЗАН отметить.

Особое внимание:
- разнонаправленные показатели одного обмена (напр. ферритин и ОЖСС при дефиците железа) должны согласовываться;
- значение вне референса, но клинически незначимое, помечать significant НЕ нужно;
- клинически значимое отклонение без пометки significant — это error.`,
    instruction: `Отрецензируй этот кейс:\n\n${asJson({
      title: draft.title,
      clinicalContext: draft.clinicalContext,
      panel: draft.panel,
      impression: draft.impression,
    })}`,
    schema: ISSUE_SCHEMA,
    what: "кейс",
  });

  return { ...normalize(parsed), usage };
}

/**
 * Проверка сценария «Виртуальный пациент».
 */
export async function verifyVpCase({ draft }) {
  if (!draft || !Array.isArray(draft.investigations)) {
    throw new ValidationError("Нет сценария для проверки");
  }

  const { parsed, usage } = await runJson({
    system: `${COMMON_RULES}

Сценарий «Виртуальный пациент»: игрок видит жалобу, сам выбирает обследования из списка и ставит диагноз. Поле necessary — эталон: обследование входит в разумный минимум.

Особое внимание:
- necessary должно стоять у обследований, без которых диагноз не поставить, и НЕ стоять у избыточных;
- у ненужных обследований результат должен быть правдоподобной нормой, а не намёком на другой диагноз;
- результаты не должны противоречить друг другу и жалобе;
- если набор necessary не позволяет прийти к диагнозу — это error.`,
    instruction: `Отрецензируй этот сценарий:\n\n${asJson({
      title: draft.title,
      presentation: draft.presentation,
      investigations: draft.investigations,
      diagnosis: draft.diagnosis,
    })}`,
    schema: ISSUE_SCHEMA,
    what: "сценарий",
  });

  return { ...normalize(parsed), usage };
}

/**
 * Проверка лучевого кейса, сгенерированного по теме (снимка ещё нет).
 * Проверяется текстовая часть и план находок — совместимы ли находки с
 * модальностью и диагнозом; сам снимок не оценивается.
 */
export async function verifyRadiologyCase({ draft, modality }) {
  if (!draft || !Array.isArray(draft.plannedFindings)) {
    throw new ValidationError("Нет кейса для проверки");
  }

  const { parsed, usage } = await runJson({
    system: `${COMMON_RULES}

Лучевой кейс: учащийся ищет находки на снимке и пишет заключение. Снимка ещё нет — автор загрузит его и разметит находки из плана. Ты проверяешь текстовую часть и план находок.

Особое внимание:
- находка должна быть в принципе видима на данной модальности исследования;
- набор находок должен соответствовать диагнозу и клиническому контексту;
- значимость (critical/major/incidental) должна соответствовать реальной опасности пропуска;
- описание «где искать» не должно противоречить диагнозу (напр. сторона поражения);
- заключение не должно упоминать находок, которых нет в плане.`,
    instruction: `Модальность исследования: ${modality}.\n\nОтрецензируй этот кейс:\n\n${asJson({
      title: draft.title,
      clinicalContext: draft.clinicalContext,
      plannedFindings: draft.plannedFindings,
      impression: draft.impression,
    })}`,
    schema: ISSUE_SCHEMA,
    what: "кейс",
  });

  return { ...normalize(parsed), usage };
}
