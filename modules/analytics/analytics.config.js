// modules/analytics/analytics.config.js
//
// Настройки доступа к PostHog для админского дашборда.
//
// ПОЧЕМУ ЧЕРЕЗ СЕРВЕР, А НЕ ИЗ БРАУЗЕРА. Читать статистику умеет только
// Personal API Key (phx_...), и он даёт доступ ко ВСЕМУ проекту — событиям,
// настройкам, другим ключам. Положить такой ключ в сборку фронтенда значит
// раздать его каждому посетителю сайта. Поэтому ключ живёт в .env сервера,
// а браузер ходит на собственные админские маршруты.
//
// Публичный ключ фронтенда (phc_..., REACT_APP_POSTHOG_KEY) — другой и умеет
// только писать события. Путать их нельзя.

export const POSTHOG_HOST = (process.env.POSTHOG_HOST || "https://eu.posthog.com").replace(/\/+$/, "");
export const POSTHOG_PROJECT_ID = process.env.POSTHOG_PROJECT_ID || "";
export const POSTHOG_API_KEY = process.env.POSTHOG_API_KEY || "";

/**
 * Настроен ли модуль. То же правило, что у клиентского analytics.js: без
 * ключа ничего не падает, просто дашборд честно говорит «не настроено».
 */
export function isAnalyticsConfigured() {
  return Boolean(POSTHOG_API_KEY && POSTHOG_PROJECT_ID);
}

// Сколько держать ответ PostHog в памяти. Query API считает деньги по объёму
// просканированных событий, а дашборд с семью вкладками легко даёт полсотни
// запросов на одно открытие страницы. Пять минут — компромисс между ценой и
// свежестью; для вкладки «сейчас на сайте» кеш отключён отдельно.
export const CACHE_TTL_MS = 5 * 60 * 1000;

// Потолок на период выборки. Запрос за три года по большому проекту может
// выполняться минутами и стоить заметных денег.
export const MAX_DAYS = 365;

// Сколько ждать ответа PostHog. Тяжёлый HogQL иногда думает долго, но висеть
// в админке дольше минуты бессмысленно.
export const REQUEST_TIMEOUT_MS = 60_000;
