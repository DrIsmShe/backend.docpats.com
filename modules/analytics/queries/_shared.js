// ВАЖНО ПРО ПОДСТАНОВКУ. Период приходит из строки запроса и попадает прямо в
// текст HogQL. Параметризованных плейсхолдеров у Query API нет, поэтому
// единственная защита — привести значение к целому числу здесь, в одном
// месте, и больше нигде не собирать SQL из пользовательского ввода.

import { MAX_DAYS } from "../analytics.config.js";

/** Целое число дней в разумных пределах. Мусор на входе → 30. */
export function safeDays(value, fallback = 30) {
  const n = Number.parseInt(value, 10);
  if (!Number.isFinite(n) || n < 1) return fallback;
  return Math.min(n, MAX_DAYS);
}

/** Граница периода: "now() - INTERVAL 30 DAY". */
export function since(days) {
  return `now() - INTERVAL ${safeDays(days)} DAY`;
}

/** Граница предыдущего такого же периода — для сравнения «было/стало». */
export function prevSince(days) {
  return `now() - INTERVAL ${safeDays(days) * 2} DAY`;
}

/**
 * Ограничение на строки в таблицах-топах. Дашборд читает человек, а не
 * машина: пятисотстрочная таблица браузеров никому не нужна, зато делает
 * ответ тяжёлым.
 */
export const TOP_LIMIT = 50;

/**
 * Строковый литерал для HogQL. Одинарная кавычка удваивается, обратный слеш
 * экранируется, управляющие символы вырезаются — так значение не может
 * закрыть строку и дописать свой SQL.
 *
 * Живёт здесь, а не в модуле-потребителе: экранирование должно быть ОДНО на
 * весь модуль. Две копии однажды разойдутся, и разойдётся именно та, что
 * защищает.
 */
export function quote(value) {
  const clean = [...String(value)]
    .filter((ch) => ch.charCodeAt(0) >= 32) // прочь управляющие символы и переводы строк
    .join("")
    .slice(0, 200)
    .split("\\").join("\\\\") // слеш первым, иначе экранируем собственные добавки
    .split("'").join("''");
  return `'${clean}'`;
}
