// Адрес чата ведёт в кабинет ПОЛУЧАТЕЛЯ, а не в кабинет врача.
//
// ЧТО БЫЛО. Уведомление о новом сообщении складывалось со ссылкой
// `/doctor/communication/<диалог>` — строкой, зашитой в код, одинаковой
// для обоих собеседников. Пациент нажимал на своё уведомление, попадал в
// зону врача, её страж спрашивал у сервера роль, получал 403 и уводил на
// страницу входа. Со стороны это выглядит как «выкинуло из системы, хотя
// я был авторизован»: человек авторизован, просто не тем, кем нужно для
// этого адреса.
//
// В логах прода это видно прямо: подряд идут «⚠️ Access denied! Role:
// patient» на /doctor-profile/doctorprofilelayout, и в базе лежат восемь
// уведомлений chat_message, где получатель — пациент, а ссылка ведёт в
// /doctor/.
//
// ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ. Тот же расчёт уже был в calls/callNotify.js для
// звонков и там сделан правильно. Две копии одного правила разошлись бы
// снова, поэтому правило одно и живёт здесь.

import User from "../../common/models/Auth/users.js";

/** Половина сайта, где у человека кабинет. */
export async function разделКабинета(userId) {
  try {
    const u = await User.findById(userId).select("role").lean();
    return u?.role === "doctor" ? "doctor" : "patient";
  } catch {
    // Не смогли определить — ведём к пациенту: у врача есть и пациентские
    // экраны, а обратное неверно.
    return "patient";
  }
}

/**
 * Ссылка на диалог в кабинете получателя.
 * Без диалога — на главную его кабинета, иначе ссылка ведёт в никуда.
 */
export function ссылкаНаЧат(раздел, dialogId) {
  return dialogId
    ? `/${раздел}/communication/${dialogId}`
    : `/${раздел}/home-page`;
}

/** Готовая ссылка для получателя: один вызов вместо двух. */
export async function ссылкаНаЧатДля(userId, dialogId) {
  return ссылкаНаЧат(await разделКабинета(userId), dialogId);
}

export default ссылкаНаЧатДля;
