// server/modules/scribe/ai/dialogueStructurer.js
// ─────────────────────────────────────────────────────────────────────
//   Диалог приёма → черновик записи в карте.
//
//   ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ НАДИКТОВКИ, И ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ.
//
//   Надиктовка — монолог врача: всё сказанное принадлежит ему и всё
//   является утверждением. Разложить её по разделам — механическая
//   работа.
//
//   Приём — диалог, и авторство здесь несёт клинический смысл:
//
//     «Я думаю, у меня воспаление лёгких» от ПАЦИЕНТА — это жалоба и
//     тревога, которую надо записать в субъективные данные. Та же фраза
//     от ВРАЧА — предварительный диагноз, который идёт в заключение.
//
//   Перепутать эти два случая — значит поставить пациенту диагноз,
//   которого врач не ставил. Поэтому расшифровка приходит сюда с
//   ПОМЕТКАМИ, кто говорил, а промпт построен вокруг одного правила:
//   утверждать может только врач.
//
//   ─── ЧТО ЗАПРЕЩЕНО ────────────────────────────────────────────────
//
//   — переносить слова пациента в объективные данные, диагноз и план;
//   — дополнять «по смыслу»: не прозвучало давление — его нет в
//     осмотре, и «АД в норме» тоже нет, это утверждение;
//   — сглаживать и обобщать: «болит невыносимо» не превращается в
//     «выраженный болевой синдром»;
//   — записывать то, что врач ПРОИЗНЁС как вопрос («аллергии есть?»)
//     как факт.
//
//   ─── ЧЕРНОВИК, А НЕ ЗАПИСЬ ────────────────────────────────────────
//
//   Результат — всегда draft. Подписывает врач, руками, обычным путём
//   модуля. Автоматически подписанная запись означала бы, что под
//   выводом модели стоит подпись человека, который его не читал.
// ─────────────────────────────────────────────────────────────────────

import { EFFORT, runJson } from "../../diagnostics/ai/runner.js";

export const PROMPT_VERSION = "scribe-2026-08-18a";

const SCHEMA = {
  type: "object",
  additionalProperties: false,
  required: ["complaints", "anamnesisMorbi", "statusPreasens", "recommendations", "notHeard"],
  properties: {
    complaints: {
      type: "string",
      description:
        "Жалобы СО СЛОВ ПАЦИЕНТА. Только то, что сказал пациент. Пустая строка, если не прозвучало.",
    },
    anamnesisMorbi: {
      type: "string",
      description:
        "История настоящего заболевания со слов пациента: когда началось, как менялось, что принимал. Пустая строка, если не прозвучало.",
    },
    anamnesisVitae: {
      type: "string",
      description:
        "Сопутствующие болезни, операции, аллергии, лекарства — со слов пациента. Пустая строка, если не прозвучало.",
    },
    statusPreasens: {
      type: "string",
      description:
        "Объективный осмотр — ТОЛЬКО то, что вслух констатировал ВРАЧ. Ничего не добавлять. Пустая строка, если врач осмотр не проговаривал.",
    },
    diagnosisText: {
      type: "string",
      description:
        "Диагноз — только если его назвал ВРАЧ. Предположение пациента диагнозом не является. Пустая строка, если врач диагноз не называл.",
    },
    recommendations: {
      type: "string",
      description:
        "Назначения и рекомендации, которые дал ВРАЧ. Пустая строка, если не прозвучало.",
    },
    notHeard: {
      type: "array",
      items: { type: "string" },
      description:
        "Разделы карты, которых в разговоре НЕ БЫЛО, и места, где речь неразборчива. Это главное поле: врач должен видеть, чего в черновике нет.",
    },
  },
};

const SYSTEM = [
  "Ты составляешь ЧЕРНОВИК записи приёма из расшифровки разговора.",
  "",
  "В расшифровке каждая реплика помечена: «Врач:» или «Пациент:».",
  "",
  "ГЛАВНОЕ ПРАВИЛО: утверждать может только врач.",
  "— слова пациента идут в жалобы и анамнез;",
  "— осмотр, диагноз и назначения — только из слов ВРАЧА;",
  "— «я думаю, у меня воспаление лёгких» от пациента это ЖАЛОБА,",
  "  а не диагноз, даже если звучит уверенно.",
  "",
  "КАТЕГОРИЧЕСКИ НЕЛЬЗЯ:",
  "— дополнять несказанное. Не прозвучало давление — его нет, и",
  "  «АД в норме» тоже нет: это утверждение, а не пропуск;",
  "— писать «без особенностей», «жалоб не предъявляет», «состояние",
  "  удовлетворительное», если этого не говорили;",
  "— обобщать и сглаживать формулировки пациента;",
  "— превращать вопрос врача в факт: «аллергии есть?» — это вопрос,",
  "  фактом становится только ответ.",
  "",
  "ОБЯЗАТЕЛЬНО перечисли в notHeard всё, чего в разговоре не было:",
  "не собран аллергоанамнез, не проговорен осмотр, не названы дозы.",
  "Врач читает черновик, чтобы дописать недостающее, — и не станет",
  "искать то, о чём не знает.",
  "",
  "ПИШИ НА ЯЗЫКЕ РАЗГОВОРА — том же, на котором говорили врач и пациент.",
  "Не переводи ни на какой другой язык, даже если он кажется более",
  "уместным для медицинского документа: слова пациента должны остаться",
  "его словами.",
  "",
  "Это черновик: подписывать будет врач.",
].join("\n");

/**
 * Собрать черновик из диалога.
 *
 * @param {string} dialogue — расшифровка с пометками говорящих
 */
export async function structureDialogue({ dialogue }) {
  if (!dialogue?.trim()) {
    throw new Error("Пустая расшифровка");
  }

  const { parsed, model } = await runJson({
    system: SYSTEM,
    schema: SCHEMA,
    what: "разговор на приёме",
    // Не механическая раскладка: нужно удержать авторство реплик.
    effort: EFFORT.analysis,
    maxTokens: 8000,
    instruction: [
      // Язык НЕ навязываем.
      //
      // Раньше сюда жёстко шло «ru», и приём на азербайджанском давал
      // русский анамнез. Это не мелочь: врач сверяет черновик с тем, что
      // помнит, а перевод на ходу — лишний слой, в котором теряются
      // именно те слова пациента, ради которых запись и велась.
      //
      // Черновик пишется на языке разговора. Перевести его врач может
      // отдельным действием — и тогда он знает, что перед ним перевод.
      "Расшифровка приёма:",
      dialogue,
    ].join("\n"),
  });

  return {
    complaints: String(parsed.complaints || "").trim(),
    anamnesisMorbi: String(parsed.anamnesisMorbi || "").trim(),
    anamnesisVitae: String(parsed.anamnesisVitae || "").trim(),
    statusPreasens: String(parsed.statusPreasens || "").trim(),
    diagnosisText: String(parsed.diagnosisText || "").trim(),
    recommendations: String(parsed.recommendations || "").trim(),
    notHeard: Array.isArray(parsed.notHeard)
      ? parsed.notHeard.map((s) => String(s).trim()).filter(Boolean).slice(0, 12)
      : [],
    model,
    promptVersion: PROMPT_VERSION,
  };
}

export default { structureDialogue, PROMPT_VERSION };
