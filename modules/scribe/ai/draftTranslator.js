// server/modules/scribe/ai/draftTranslator.js
// ─────────────────────────────────────────────────────────────────────
//   Перевод черновика приёма на другой язык — ПО ТРЕБОВАНИЮ ВРАЧА.
//
//   Черновик собирается на языке разговора: врач сверяет его с тем, что
//   помнит, и лишний слой перевода на этом шаге стирает именно те слова
//   пациента, ради которых запись и велась.
//
//   Но карта клиники может вестись на другом языке, и тогда перевод
//   нужен — отдельным, ЯВНЫМ действием. Разница существенная: врач
//   знает, что перед ним перевод, и читает его соответственно.
//
//   ─── ЧТО ЗАПРЕЩЕНО ПЕРЕВОДЧИКУ ────────────────────────────────────
//
//   Перевод медицинского текста — не пересказ. Здесь запрещено ровно то
//   же, что и сборщику черновика, и по тем же причинам:
//
//   — дополнять. Не было в исходнике температуры — не появится и в
//     переводе, включая «без лихорадки»;
//   — сглаживать. «Болит невыносимо» остаётся невыносимо, а не
//     становится «выраженным болевым синдромом»: врач написал так, как
//     сказал пациент, и это его решение, а не стилистическая небрежность;
//   — «улучшать» формулировки до канцелярита медицинских документов;
//   — переводить названия препаратов, дозы и единицы. Парацетамол
//     остаётся парацетамолом, 500 мг остаются 500 мг.
//
//   Пустое поле остаётся пустым: «не заполнено» переводу не подлежит.
// ─────────────────────────────────────────────────────────────────────

import { EFFORT, runJson } from "../../diagnostics/ai/runner.js";

export const PROMPT_VERSION = "scribe-tr-2026-08-18a";

// Языки интерфейса платформы. Список закрытый: перевод на язык, которого
// нет в интерфейсе, некому потом прочитать.
export const TRANSLATABLE = {
  ru: "русский",
  en: "английский",
  az: "азербайджанский",
  tr: "турецкий",
  ar: "арабский",
};

const FIELDS = [
  "complaints",
  "anamnesisMorbi",
  "anamnesisVitae",
  "statusPreasens",
  "diagnosisText",
  "recommendations",
];

const SCHEMA = {
  type: "object",
  additionalProperties: false,
  required: FIELDS,
  properties: Object.fromEntries(
    FIELDS.map((f) => [
      f,
      {
        type: "string",
        description: `Перевод поля ${f}. Пустая строка, если в исходнике пусто.`,
      },
    ]),
  ),
};

const SYSTEM = [
  "Ты переводишь ЧЕРНОВИК записи приёма на другой язык.",
  "",
  "Это перевод, а не пересказ и не редактура. Категорически нельзя:",
  "— добавлять то, чего нет в исходнике, включая отрицания",
  "  («без лихорадки», «отёков нет») — это утверждения, а не пропуски;",
  "— сглаживать формулировки: «болит невыносимо» остаётся невыносимо;",
  "— «улучшать» текст до канцелярита медицинских документов;",
  "— переводить названия препаратов, дозы, единицы измерения и коды.",
  "",
  "Пустое поле оставляй пустым: «не заполнено» переводу не подлежит.",
  "",
  "Медицинские термины переводи принятыми в целевом языке эквивалентами,",
  "а не буквально. Если устоявшегося эквивалента нет — оставь исходный",
  "термин: непонятный врачу перевод хуже понятного оригинала.",
].join("\n");

/**
 * Перевести поля черновика.
 *
 * @param {object} fields — то, что СЕЙЧАС в полях (уже с правками врача)
 * @param {string} to — код целевого языка
 */
export async function translateDraft({ fields, to }) {
  const target = TRANSLATABLE[to];
  if (!target) {
    throw new Error(`Перевод на «${to}» не поддерживается`);
  }

  // Пустые поля в модель не отправляем: платить за перевод пустоты
  // незачем, а вернуть её мы умеем и сами.
  const filled = FIELDS.filter((f) => String(fields?.[f] || "").trim());
  if (!filled.length) {
    return { fields: Object.fromEntries(FIELDS.map((f) => [f, ""])), model: null };
  }

  const body = filled
    .map((f) => `${f}: ${String(fields[f]).trim()}`)
    .join("\n\n");

  const { parsed, model } = await runJson({
    system: SYSTEM,
    schema: SCHEMA,
    what: "перевод черновика приёма",
    // Перевод — не рассуждение, но и не механика: термины требуют
    // выбора эквивалента.
    effort: EFFORT.extraction,
    maxTokens: 6000,
    instruction: [
      `Переведи на ${target} язык.`,
      "",
      "Поля черновика:",
      body,
    ].join("\n"),
  });

  return {
    fields: Object.fromEntries(
      FIELDS.map((f) => [f, String(parsed[f] || "").trim()]),
    ),
    model,
    promptVersion: PROMPT_VERSION,
  };
}

export default { translateDraft, TRANSLATABLE, PROMPT_VERSION };
