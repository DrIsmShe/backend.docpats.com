// ─────────────────────────────────────────────────────────────────────
//   Ответы анкеты → связный анамнез ДЛЯ ВРАЧА.
//
//   ЧТО МОДЕЛЬ ЗДЕСЬ ДЕЛАЕТ. Складывает разрозненные ответы в текст,
//   который врач прочитает за двадцать секунд вместо восьми полей, и
//   называет вопросы, которые из рассказа следуют, но заданы не были.
//
//   ЧЕГО НЕ ДЕЛАЕТ И ПОЧЕМУ:
//
//   — не ставит диагноз и не называет вероятные болезни. Названный
//     диагноз работает как якорь: врач, прочитавший «похоже на
//     гастрит», ищет подтверждение, а не проверяет альтернативы. Это
//     не гипотетический вред — так устроено человеческое внимание, и
//     подсказка до осмотра опаснее подсказки после;
//   — не назначает обследований и лечения;
//   — не добавляет фактов. Пациент не сказал про температуру — в
//     анамнезе её нет, и «без лихорадки» тоже нет: это утверждение, а
//     не пропуск;
//   — не сглаживает. «Боль невыносимая» остаётся невыносимой, а не
//     становится «выраженной».
//
//   ТРЕВОЖНЫЕ ПРИЗНАКИ МОДЕЛИ НЕ ДОВЕРЕНЫ. Их пациент отмечает сам в
//   списке, и они считаются кодом. Вылавливать одышку из свободного
//   текста — задача, в которой пропуск стоит слишком дорого.
// ─────────────────────────────────────────────────────────────────────

import { EFFORT, runJson } from "../../diagnostics/ai/runner.js";

export const PROMPT_VERSION = "previsit-2026-08-17a";

const SCHEMA = {
  type: "object",
  additionalProperties: false,
  required: ["narrative", "clarify"],
  properties: {
    narrative: {
      type: "string",
      description:
        "Анамнез со слов пациента: 3–6 предложений в третьем лице, в порядке жалоба → начало → динамика → что принимал → сопутствующее. Только то, что пациент сказал.",
    },
    clarify: {
      type: "array",
      maxItems: 5,
      items: { type: "string" },
      description:
        "Вопросы, которые стоит задать на приёме и которые следуют из рассказа. Не диагнозы, не назначения. Пустой массив, если рассказ полный.",
    },
  },
};

const SYSTEM = [
  "Ты складываешь ответы анкеты пациента в анамнез для врача.",
  "",
  "КАТЕГОРИЧЕСКИ НЕЛЬЗЯ:",
  "— ставить диагноз, называть вероятные болезни, даже как предположение;",
  "— назначать обследования, анализы и лечение;",
  "— добавлять то, чего пациент не говорил, включая отрицания",
  "  («без температуры», «отёков нет») — это утверждения, а не пропуски;",
  "— смягчать формулировки пациента: «невыносимая» остаётся невыносимой.",
  "",
  "НУЖНО:",
  "— писать в третьем лице, сухо, как пишут анамнез: «Жалобы на…»;",
  "— сохранять слова пациента там, где они точнее пересказа;",
  "— в clarify называть вопросы, которые из рассказа следуют, но не",
  "  заданы: уточнение характера боли, связи с едой, приёма лекарств.",
  "",
  "Врач прочитает это до осмотра. Названный диагноз стал бы якорем,",
  "который мешает проверять альтернативы, — поэтому его здесь нет.",
].join("\n");

/**
 * Собрать анамнез.
 *
 * @param {object[]} rows — [{ label, value }] в порядке вопросов
 * @param {string} [language]
 */
export async function composeIntake({ rows, language = "ru" }) {
  const body = rows
    .filter((r) => r.value)
    .map((r) => `${r.label}: ${r.value}`)
    .join("\n");

  const { parsed, model } = await runJson({
    system: SYSTEM,
    schema: SCHEMA,
    what: "анкета перед приёмом",
    effort: EFFORT.extraction,
    // Анамнез, который врач читает до осмотра, должен занимать абзац.
    maxTokens: 3000,
    instruction: [
      `Язык ответа: ${language}.`,
      "",
      "Ответы пациента:",
      body,
    ].join("\n"),
  });

  return {
    narrative: String(parsed.narrative || "").trim(),
    clarify: Array.isArray(parsed.clarify)
      ? parsed.clarify.map((s) => String(s).trim()).filter(Boolean).slice(0, 5)
      : [],
    model,
    promptVersion: PROMPT_VERSION,
  };
}

export default { composeIntake, PROMPT_VERSION };
