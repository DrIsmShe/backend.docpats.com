/**
 * Тревожные признаки, о которых нужно сказать пациенту НЕМЕДЛЕННО, не
 * дожидаясь приёма.
 *
 * Список короткий и намеренно грубый: это не диагностика, а правило
 * «при таком не ждут записи через неделю». Ошибка в сторону лишней
 * тревоги здесь допустима, в обратную — нет.
 */
export const URGENT = new Set([
  "chest_pain",
  "breath",
  "faint",
  "bleeding",
  "numbness",
  "speech",
]);

/** Ярлык варианта — чтобы врач читал слова, а не коды. */
export function labelFor(questionId, value) {
  const q = QUESTIONS.find((x) => x.id === questionId);
  if (!q?.options) return value;
  return q.options.find((o) => o.value === value)?.label || value;
}

export default { QUESTIONS, URGENT, labelFor };
