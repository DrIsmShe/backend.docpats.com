// server/modules/videra/pass.js
//
// Подпись пропуска в студию медицинских фильмов DP-Videra.
//
// ЗАЧЕМ ПРОПУСК. Студия живёт отдельной службой на другом сервере и своей
// базы пользователей не имеет. Вместо второй регистрации DocPats выдаёт
// подписанную строку: кто это, из какой клиники, по какому тарифу. Студия
// проверяет подпись тем же ключом и впускает.
//
// ПОЧЕМУ HMAC, А НЕ JWT. Библиотека здесь ничего не добавила бы: полей
// пять, срок один, алгоритм один. Зато обе стороны — и этот сервер, и
// служба на другом — считают подпись одинаково, без общей зависимости.
//
// ПЯТЬ МИНУТ. Это передача из рук в руки, а не сессия. Осевший в истории
// браузера или в журнале nginx, к утру пропуск уже ничего не открывает;
// дальше человека держит своя печенька студии.
//
// КЛЮЧ. Тот же, что в /etc/dp-videra.env на сервере студии. Живёт только
// в переменной окружения: код лежит в git и виден всем, у кого есть к нему
// доступ.

import crypto from "node:crypto";

// ОБА ЗНАЧЕНИЯ ЧИТАЮТСЯ ПРИ ВЫЗОВЕ, А НЕ ПРИ ЗАГРУЗКЕ. В главном index.js
// dotenv.config() стоит ниже импортов, а импорты в ESM выполняются раньше
// любого кода модуля: на момент загрузки этого файла окружения ещё нет.
// Константа молча взяла бы запасное значение и никогда бы не обновилась.

/** Адрес студии. Врач и пациент видят только его. */
export function студия() {
  return process.env.DPVIDERA_URL || "https://docpats.com/dp-videra";
}

/** Ключ, общий со студией. Нет ключа — кнопки не будет вовсе. */
export function ключ() {
  return process.env.DPVIDERA_SECRET || "";
}

export function студияВключена() {
  return !!ключ();
}

function подпись(что) {
  return crypto.createHmac("sha256", ключ()).update(что).digest("base64url");
}

/**
 * Собрать пропуск.
 *
 * @param {object}  кто
 * @param {string}  кто.id       кто это в DocPats — единственное обязательное
 * @param {string} [кто.name]    как зовут: покажется в углу студии
 * @param {string} [кто.clinic]  клиника: попадёт в подпись фильма
 * @param {string} [кто.plan]    тариф: по нему студия решает про водяной знак
 * @param {number} [живёт]       секунд; больше пяти минут не нужно
 */
export function собратьПропуск(кто, живёт = 300) {
  if (!ключ()) throw new Error("не задан DPVIDERA_SECRET");
  if (!кто || !кто.id) throw new Error("в пропуске должно быть, кто это");

  const тело = Buffer.from(
    JSON.stringify({
      id: String(кто.id),
      name: String(кто.name || ""),
      clinic: String(кто.clinic || ""),
      plan: String(кто.plan || ""),
      до: Math.floor(Date.now() / 1000) + живёт,
    }),
    "utf8",
  ).toString("base64url");

  return тело + "." + подпись(тело);
}

/** Готовая ссылка для кнопки «Снять фильм». */
export function ссылкаНаСтудию(кто, живёт = 300) {
  return студия() + "/enter?token=" + encodeURIComponent(собратьПропуск(кто, живёт));
}
