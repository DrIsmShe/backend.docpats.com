// Подмодуль «Эхокардиография».
//
// Отдельно от ультразвука (us) намеренно. ЭхоКГ — исследование движущегося
// сердца: половина смысла в динамике (сократимость, потоки, клапанная
// регургитация), которой в стоп-кадре просто нет. Протокол разбора и красные
// флаги у неё свои, и валить их в общий ультразвук значит потерять и то и
// другое.

import { registerModality } from "../core/services/registry.js";

export default registerModality({
  key: "echo",
  title: "Эхокардиография",
  group: "Функциональная диагностика",
  purpose:
    "Разбор ЭхоКГ по протоколу и снимку: камеры, клапаны, сократимость, перикард",
  accepts: ["report", "image", "video", "text"],
  capabilities: ["text", "image"],
  analyzer: "report",

  // Граница здесь жёстче, чем у обычного УЗИ: фракция выброса и градиенты —
  // измерения, а не впечатление от картинки. Врач должен понимать, что цифры
  // берутся из протокола, а не «считаны» моделью со стоп-кадра.
  binaryNote:
    "Присланный кадр — стоп-кадр движущегося сердца. Модель видит на нём анатомию: размеры камер, состояние клапанов, наличие выпота. Она НЕ измеряет фракцию выброса, градиенты и потоки — это делает прибор в момент исследования, и брать их надо из протокола. Сократимость по одному кадру не оценивается: для этого нужна запись, а не картинка.",

  checklist: [
    "Размеры камер и толщина стенок",
    "Глобальная и локальная сократимость, фракция выброса из протокола",
    "Клапаны: створки, стенозы, регургитация и её степень",
    "Диастолическая функция",
    "Перикард: выпот, признаки сдавления",
    "Аорта и лёгочная гипертензия",
    "Сопоставление с прошлым исследованием и с жалобами",
  ],

  redFlags: [
    "Признаки тампонады сердца",
    "Тромб в полости сердца или подвижное образование",
    "Критический стеноз клапана",
    "Расслоение аорты или её острое расширение",
    "Тяжёлое снижение фракции выброса",
    "Признаки острой перегрузки правых отделов",
  ],
});
