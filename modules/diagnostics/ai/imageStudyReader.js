// ЧТЕНИЕ САМОГО СНИМКА, а не текста на нём.
//
// documentReader переписывает то, что НАПЕЧАТАНО на бланке. Этот файл делает
// другое: смотрит на изображение и описывает, что на нём видно, по протоколу
// модальности.
//
// ГДЕ ЭТО ВЫПОЛНЯЕТСЯ И ПОЧЕМУ ИМЕННО ТАМ. В момент загрузки файла, пока
// буфер ещё в памяти запроса. Снимки в деле НЕ ХРАНЯТСЯ — файл уходит на
// распознавание и забывается, в дело попадает только текст. Это осознанное
// решение о минимизации PHI, и ради чтения изображений его ломать нельзя:
// хранилище снимков живого пациента — совсем другой уровень ответственности,
// чем хранилище их описаний. Поэтому читаем здесь и кладём в дело ОПИСАНИЕ.
//
// ЧЕСТНЫЕ ГРАНИЦЫ, зашитые в промпт, а не только написанные в интерфейсе:
//
//   1. Это НЕ заключение. Формулировки — «что видно» и «что проверить»,
//      никогда «диагноз такой-то».
//   2. НИКОГДА не отрицать патологию. «Патологии не выявлено» по одной
//      картинке — самое опасное, что здесь можно написать: врач прочтёт это
//      как норму и не назначит исследование.
//   3. КТ и МРТ — это серия из сотен срезов с окнами и плотностями в HU.
//      Присланный JPEG — одна реконструкция в одном окне, уже без HU. Модель
//      обязана сказать об этом сама, а не делать вид, что видит исследование.
//   4. Не выдумывать то, чего не видно: нет разметки — нет размеров.

import { EFFORT, PROMPT_VERSION, runJson, str, list } from "./runner.js";

/** Модальности, где присланная картинка — это лишь фрагмент исследования. */
const SERIES_MODALITIES = new Set(["ct", "mri"]);

const SYSTEM = [
  "Ты помогаешь врачу посмотреть на медицинское изображение вторым взглядом.",
  "",
  "Ты НЕ ставишь диагноз и НЕ пишешь заключение. Ты описываешь, что видно на",
  "изображении, и что из увиденного стоит проверить. Заключение пишет врач.",
  "",
  "Жёсткие правила:",
  "1. Описывай только то, что действительно видно. Не додумывай структуры,",
  "   которых нет в кадре, и не переноси сюда типичную картину болезни.",
  "2. НИКОГДА не пиши, что патологии нет. Отсутствие видимых изменений на",
  "   одном изображении не означает их отсутствия у пациента. Если ничего",
  "   не бросается в глаза — так и скажи: «на этом изображении явных",
  "   изменений не вижу», и это не отрицание патологии.",
  "3. Размеры указывай, только если в кадре есть шкала или линейка. Иначе",
  "   описывай относительно анатомических ориентиров.",
  "4. Отдельно назови, что мешает смотреть: проекция, укладка, артефакты,",
  "   качество, обрезанный край, отсутствие сравнения.",
  "5. Пиши по-русски, языком врачебной записи, без общих фраз.",
].join("\n");

const SCHEMA = {
  type: "object",
  additionalProperties: false,
  required: ["modalityGuess", "whatIsVisible", "observations", "limits"],
  properties: {
    modalityGuess: {
      type: "string",
      description: "Что это за исследование и проекция, судя по изображению",
    },
    whatIsVisible: {
      type: "string",
      description: "Что в кадре: область, укладка, качество. Две-три фразы.",
    },
    observations: {
      type: "array",
      minItems: 0,
      description: "Что обращает на себя внимание. Не больше 10.",
      items: {
        type: "object",
        additionalProperties: false,
        required: ["finding", "where", "confidence"],
        properties: {
          finding: { type: "string", description: "Что видно" },
          where: { type: "string", description: "Где именно, по анатомии" },
          confidence: {
            type: "string",
            enum: ["low", "moderate", "high"],
            description: "Насколько уверенно это видно НА ЭТОМ изображении",
          },
          verify: {
            type: "string",
            description: "Чем это подтвердить или опровергнуть",
          },
        },
      },
    },
    limits: {
      type: "array",
      minItems: 0,
      description: "Что мешает смотреть: проекция, артефакты, качество, обрезка",
      items: { type: "string" },
    },
  },
};

/**
 * Читает изображение исследования.
 *
 * @param {object} p
 * @param {Buffer} p.buffer
 * @param {string} p.mimeType
 * @param {object} [p.modality]  модальность из реестра (нужен checklist)
 * @param {string} [p.hint]      что это, по словам врача
 * @param {boolean} [p.sheet]    картинка — сетка срезов одной серии, а не один кадр
 */
export async function readImageStudy({
  buffer,
  mimeType,
  modality = null,
  hint = "",
  sheet = false,
}) {
  const isSeries = modality && SERIES_MODALITIES.has(modality.key);

  const instruction = [
    modality ? `Модальность по данным дела: ${modality.title}.` : null,
    hint ? `Врач уточняет: ${str(hint, 300)}` : null,
    "",
    // Сетку срезов надо назвать сеткой раньше всего остального: если модель
    // примет её за один кадр, она опишет двенадцать плиток как двенадцать
    // образований в одной голове. Ошибка не косметическая — она клиническая.
    sheet
      ? [
          "ВАЖНО: перед тобой НЕ один снимок, а СВОДНАЯ СЕТКА из нескольких срезов",
          "ОДНОЙ серии КТ/МРТ, выбранных равномерно по всему исследованию. Каждая",
          "плитка — отдельный срез одного и того же пациента на разном уровне.",
          "Читай по плиткам слева направо и сверху вниз; цифра в углу плитки —",
          "номер среза в серии, ссылайся на находки по этим номерам и говори, с",
          "какого по какой срез изменение прослеживается.",
          "Плитки НЕ являются разными объектами: не описывай их как несколько",
          "образований и не суммируй одну и ту же находку по каждому срезу.",
          "Между показанными срезами есть непросмотренные, и это выборка, а не",
          "исследование целиком — скажи это в limits.",
        ].join("\n")
      : isSeries
        ? [
            "ВАЖНО: это КТ или МРТ — исследование из сотен срезов с разными окнами",
            "и плотностями. Тебе прислали ОДНО изображение: одну реконструкцию в",
            "одном окне, уже без данных о плотности. Ты смотришь фрагмент, а не",
            "исследование. Скажи это прямо в limits и не делай выводов об",
            "исследовании целиком.",
          ].join("\n")
        : null,
    "",
    modality?.checklist?.length
      ? [
          "Пройди глазами по протоколу этой модальности и скажи, что видно по",
          "каждому пункту, который вообще попал в кадр:",
          ...modality.checklist.map((c, i) => `${i + 1}. ${c}`),
        ].join("\n")
      : null,
    "",
    "Опиши, что видно, и что из этого стоит проверить. Не ставь диагноз.",
  ]
    .filter(Boolean)
    .join("\n");

  const { parsed, model } = await runJson({
    system: SYSTEM,
    schema: SCHEMA,
    what: "изображение исследования",
    // Смотреть на снимок — это рассуждение, в отличие от переписывания
    // напечатанного. Уровень как у разбора, а не как у распознавания.
    effort: EFFORT.analysis,
    maxTokens: 16000,
    content: [
      { type: "image", source: { type: "base64", media_type: mimeType, data: buffer.toString("base64") } },
      { type: "text", text: instruction },
    ],
  });

  return {
    modalityGuess: str(parsed.modalityGuess, 300),
    whatIsVisible: str(parsed.whatIsVisible, 2000),
    observations: (parsed.observations ?? []).slice(0, 10).map((o) => ({
      finding: str(o.finding, 500),
      where: str(o.where, 300),
      confidence: ["low", "moderate", "high"].includes(o.confidence) ? o.confidence : "low",
      verify: str(o.verify, 500),
    })),
    limits: list(parsed.limits, 10, 300),
    sheet,
    model,
    promptVersion: PROMPT_VERSION,
  };
}

/**
 * Описание изображения в виде текста для дела.
 *
 * В дело кладётся именно текст — так это проходит по уже работающему пути
 * разбора и, что важнее, отображается в текущем интерфейсе без единой правки
 * на клиенте.
 *
 * Заголовок обязателен и однозначен: читая протокол дела через полгода, врач
 * должен видеть, что это прочитала модель по картинке, а не написал коллега.
 */
export function renderImageStudyText(read) {
  const lines = [
    "── ПРОЧИТАНО С ИЗОБРАЖЕНИЯ МОДЕЛЬЮ (не заключение врача) ──",
    "",
    read.modalityGuess ? `Что это: ${read.modalityGuess}` : null,
    read.whatIsVisible ? `В кадре: ${read.whatIsVisible}` : null,
  ];

  if (read.observations.length) {
    const conf = { high: "уверенно", moderate: "предположительно", low: "неотчётливо" };
    lines.push("", "Обращает на себя внимание:");
    for (const o of read.observations) {
      lines.push(
        `• ${o.finding}${o.where ? ` — ${o.where}` : ""} (${conf[o.confidence]})` +
          (o.verify ? `\n  проверить: ${o.verify}` : ""),
      );
    }
  } else {
    // Формулировка выбрана намеренно: не «патологии нет», а «на этом
    // изображении не вижу». Разница между ними — цена пропущенного диагноза.
    lines.push(
      "",
      read.sheet
        ? "Явных изменений на просмотренных срезах не отмечено."
        : "Явных изменений на этом изображении не отмечено.",
    );
    lines.push("Это НЕ означает отсутствия патологии у пациента.");
  }

  if (read.limits.length) {
    lines.push("", "Что мешает смотреть:");
    for (const l of read.limits) lines.push(`• ${l}`);
  }

  lines.push(
    "",
    read.sheet
      ? "Описание получено моделью по ВЫБОРКЕ срезов серии (не по всем) и подлежит проверке врачом."
      : "Описание получено моделью по одному изображению и подлежит проверке врачом.",
  );

  return lines.filter((l) => l !== null).join("\n");
}
