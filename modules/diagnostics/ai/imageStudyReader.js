//
// ЧТЕНИЕ САМОГО СНИМКА, а не текста на нём.
//
// documentReader переписывает то, что НАПЕЧАТАНО на бланке. Этот файл делает
// другое: смотрит на изображение и описывает, что на нём видно, по протоколу
// модальности.
//
// ГДЕ ЭТО ВЫПОЛНЯЕТСЯ И ПОЧЕМУ ИМЕННО ТАМ. В момент загрузки файла, пока
// буфер ещё в памяти запроса. Снимки в деле НЕ ХРАНЯТСЯ — файл уходит на
// распознавание и забывается, в дело попадает только текст. Это осознанное
// решение о минимизации PHI, и ради чтения изображений его ломать нельзя:
// хранилище снимков живого пациента — совсем другой уровень ответственности,
// чем хранилище их описаний. Поэтому читаем здесь и кладём в дело ОПИСАНИЕ.
//
// ЧЕСТНЫЕ ГРАНИЦЫ, зашитые в промпт, а не только написанные в интерфейсе:
//
//   1. Это НЕ заключение. Формулировки — «что видно» и «что проверить»,
//      никогда «диагноз такой-то».
//   2. НИКОГДА не отрицать патологию. «Патологии не выявлено» по одной
//      картинке — самое опасное, что здесь можно написать: врач прочтёт это
//      как норму и не назначит исследование.
//   3. КТ и МРТ — это серия из сотен срезов с окнами и плотностями в HU.
//      Присланный JPEG — одна реконструкция в одном окне, уже без HU. Модель
//      обязана сказать об этом сама, а не делать вид, что видит исследование.
//   4. Не выдумывать то, чего не видно: нет разметки — нет размеров.

import { EFFORT, PROMPT_VERSION, runJson, str, list } from "./runner.js";
import { imageText, languageRule, normalizeLang } from "./language.js";

/** Модальности, где присланная картинка — это лишь фрагмент исследования. */
const SERIES_MODALITIES = new Set(["ct", "mri"]);

/**
 * Сколько распознанного текста считать бланком.
 *
 * Порог грубый и таким и задуман: он отделяет пустую плёнку от заполненного
 * документа, а не измеряет содержательность. На снимках обычно есть подписи —
 * проекция, дата, имя аппарата, — и на плёнке с полным набором маркеров их
 * набирается больше порога. Поэтому порог не единственное основание смотреть
 * на снимок: см. shouldReadImage.
 */
const MIN_USABLE_TEXT = 40;

/**
 * Смотреть ли на само изображение, а не только на текст с него.
 *
 * Вынесено из контроллера отдельной функцией, потому что это РЕШЕНИЕ, а не
 * деталь: от него зависит, увидит ли врач осмотр снимка вообще. Условие,
 * спрятанное в теле обработчика, один раз уже подвело — КТ с маркерами
 * проекции выглядела заполненным бланком и оставалась непросмотренной.
 *
 * @param {object} p
 * @param {string} p.mimeType              тип присланного файла
 * @param {boolean} [p.forced]             врач нажал «Прочитать снимок»
 * @param {boolean} [p.modalitySupportsImages] направление умеет смотреть картинки
 * @param {string} [p.extractedText]       что удалось вычитать из файла текстом
 */
export function shouldReadImage({
  mimeType,
  forced = false,
  modalitySupportsImages = false,
  extractedText = "",
}) {
  // PDF — многостраничный документ, а не снимок. Его путь текстовый.
  if (mimeType === "application/pdf") return false;

  // Прямое указание врача сильнее любой догадки: он видит файл, мы — нет.
  if (forced) return true;

  // Направление выбрано и умеет смотреть — значит смотреть и надо.
  if (modalitySupportsImages) return true;

  // Последнее основание: текста в файле практически нет. Тогда осмотр — это
  // единственный способ хоть что-то из файла получить.
  return String(extractedText ?? "").trim().length < MIN_USABLE_TEXT;
}

