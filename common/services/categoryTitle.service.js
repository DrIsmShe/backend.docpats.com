// server/common/services/categoryTitle.service.js
//
// Название рубрики статьи на пяти языках.
//
// ПОЧЕМУ ЭТОГО НЕ БЫЛО. У рубрики врачебных статей одно поле `name` —
// строка на том языке, на котором её завели. Аналитика ИИ свои рубрики
// («Гематология», «Эндокринология») показывает переведёнными, потому что
// у неё это специальность из закрытого справочника со словарём в коде. А
// рубрики врачей заводит администратор, произвольным текстом, и словаря
// для них быть не может — только перевод.
//
// ПУСТОЕ ПОЛЕ ЧЕСТНЕЕ ПОДДЕЛКИ. Если перевод не удался или пришёл не на том
// алфавите, поле остаётся пустым и интерфейс покажет исходное название.
// Кириллица под видом арабского выглядит переведённой — и потому не будет
// замечена никогда.
//
// ОДНО СЛОВО — НЕ СТАТЬЯ. Переводчик рассчитан на текст; названию рубрики
// нужен контекст, иначе «Разное» уезжает в турецкий как имя собственное.
// Контекст передаётся заголовком запроса.

const ЯЗЫКИ = ["ru", "en", "az", "tr", "ar"];

/* Алфавиты целевых языков. Проверка грубая, но ловит главное — ответ,
   оставшийся на языке оригинала. */
const АЛФАВИТ = {
  ru: /[а-яё]/i,
  en: /[a-z]/i,
  az: /[a-zçəğıöşü]/i,
  tr: /[a-zçğıöşü]/i,
  ar: /[؀-ۿ]/,
};

/** Похоже ли на нужный язык. Для латинских — ещё и «не кириллица». */
export function похожеНаЯзык(текст, язык) {
  const проверка = АЛФАВИТ[язык];
  if (!проверка || !проверка.test(текст)) return false;
  if (язык !== "ru" && /[а-яё]/i.test(текст)) return false;
  return true;
}

/**
 * Дополнить название переводами на недостающие языки.
 *
 * @param {{ru?: string} & Record<string, string>} title
 * @param {string} [исходный] язык, на котором название уже есть
 * @returns {Promise<Record<string, string>>}
 */
export async function перевестиНазваниеРубрики(title, исходный = "ru") {
  const готово = { ...(title || {}) };
  const источник = String(готово[исходный] || "").trim();
  if (!источник) return готово;

  const нужны = ЯЗЫКИ.filter(
    (л) => l_нужен(л, исходный) && !String(готово[л] || "").trim(),
  );
  if (!нужны.length) return готово;

  const { translate } = await import(
    "../../modules/translation/translation.provider.js"
  );

  for (const язык of нужны) {
    try {
      const { content } = await translate({
        title: "Название рубрики медицинских статей",
        content: источник,
        fromLanguage: исходный,
        toLanguage: язык,
      });

      const текст = String(content || "").trim().slice(0, 80);
      if (текст && похожеНаЯзык(текст, язык)) {
        готово[язык] = текст;
      } else if (текст) {
        console.warn(
          `[categories] перевод рубрики на ${язык} не похож на язык: «${текст}»`,
        );
      }
    } catch (err) {
      console.warn(`[categories] рубрика на ${язык}:`, err?.message);
    }
  }

  return готово;
}

function l_нужен(язык, исходный) {
  return язык !== исходный;
}

/** Название на языке читателя; нет перевода — исходное. */
export function названиеРубрики(категория, язык = "ru") {
  if (!категория) return "";
  const переводы = категория.title || {};
  return (
    String(переводы[язык] || "").trim() ||
    String(переводы.ru || "").trim() ||
    категория.name ||
    ""
  );
}

export default { перевестиНазваниеРубрики, названиеРубрики, похожеНаЯзык };
