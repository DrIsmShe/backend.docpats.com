// server/common/ai/aiSettings.model.js
//
// Какой моделью работает платформа — одна запись на всю систему.
//
// ЗАЧЕМ В БАЗЕ, А НЕ В .env. Переменная окружения меняется только выкладкой
// и рестартом: пока кто-то дойдёт до сервера, врачи уже читают непереведённые
// статьи. Здесь же смена провайдера — это нажатие в админке, и оно
// действует на следующем задании, без перезапуска.
//
// ENV ОСТАЁТСЯ ЗНАЧЕНИЕМ ПО УМОЛЧАНИЮ. Пустая база не должна означать
// «модели нет»: до первого захода в админку всё работает так, как записано
// в окружении, и ровно так же — если база на минуту недоступна.
//
// ЧТО ЗДЕСЬ НЕ ХРАНИТСЯ. Ключи API. Они остаются в окружении сервера:
// админка показывает, ЧТО выбрано, а не чем мы платим. Ключ, попавший в
// базу, попадает и в резервную копию, и в выгрузку — а вынуть его оттуда
// потом нельзя.

import mongoose from "mongoose";

/** Кого можно выбрать. Список закрытый: клиент под провайдера пишется кодом. */
export const ПРОВАЙДЕРЫ = ["anthropic", "openai"];

/**
 * Назначения — задачи, у каждой свой провайдер и своя модель.
 *
 * Разделение нужно, потому что провайдеры умеют разное: распознавание речи
 * и рисование картинок есть только у OpenAI, и переключить их «на Claude»
 * нельзя — не потому что мы не хотим, а потому что такого API нет.
 */
export const НАЗНАЧЕНИЯ = [
  "translation", // перевод статей и материалов
  "chat", // перевод сообщений в чате
  "summary", // выжимки и аннотации
  "consultation", // ИИ-консультации и разборы
  "speech", // расшифровка речи — только OpenAI
  "image", // генерация изображений — только OpenAI
];

/** Назначения, которые Anthropic не выполняет: выбор там фиктивный. */
export const ТОЛЬКО_OPENAI = ["speech", "image"];

const назначениеSchema = new mongoose.Schema(
  {
    provider: { type: String, enum: ПРОВАЙДЕРЫ, default: null },
    /* Пустая модель означает «по умолчанию провайдера»: держать здесь
       конкретное имя обязательным значило бы ломать платформу каждый раз,
       когда модель снимают с обслуживания. */
    model: { type: String, trim: true, default: "" },
  },
  { _id: false },
);

const aiSettingsSchema = new mongoose.Schema(
  {
    key: { type: String, default: "ai", unique: true },

    /* Провайдер по умолчанию — для всех назначений, где не выбрано своё. */
    provider: { type: String, enum: ПРОВАЙДЕРЫ, default: "anthropic" },

    /* Точечные переопределения по назначениям. */
    tasks: {
      type: Map,
      of: назначениеSchema,
      default: () => new Map(),
    },

    updatedBy: { type: mongoose.Schema.Types.ObjectId, default: null },
    lastChange: { type: String, trim: true, default: "" },
  },
  { timestamps: true },
);

export default mongoose.models.AiSettings ||
  mongoose.model("AiSettings", aiSettingsSchema, "ai_settings");
