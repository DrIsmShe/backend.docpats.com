//
// Кто спрашивает — спрашивает здесь. Модуль перевода, чат, выжимки,
// консультации: каждый зовёт `провайдерДля("translation")` и получает
// имя провайдера и модель. Раньше это знание было размазано по десятку
// файлов: в каждом свой `new OpenAI()` и своя строка с моделью, и когда у
// OpenAI кончились деньги, чинить пришлось бы каждый файл отдельно.
//
// ТРИ ИСТОЧНИКА, В ЭТОМ ПОРЯДКЕ:
//   1. Админка (коллекция ai_settings) — меняется нажатием, действует сразу.
//   2. Переменная окружения — что стоит на сервере.
//   3. Значение по умолчанию в коде — чтобы платформа работала на голой базе.
//
// РАЗНЫЕ ЧАСТИ — РАЗНЫЕ МОДЕЛИ, И ЭТО НЕ ПРИХОТЬ. Перевод статьи и
// клиническая консультация — задачи разного веса: первой хватает быстрой
// модели, второй нужна сильная. А распознавание речи и рисование картинок
// у Anthropic не существует вовсе, и «переключить их на Claude» нельзя —
// такие назначения помечены отдельно и остаются на OpenAI.
//
// КЭШ НА НЕСКОЛЬКО СЕКУНД. Настройку спрашивают на каждое задание перевода,
// а их в очереди сотни; запрос к базе на каждое — лишняя нагрузка. Пять
// секунд жизни кэша дают и мгновенное на глаз переключение, и один запрос
// вместо сотни.
//
// СБОЙ БАЗЫ НЕ ОСТАНАВЛИВАЕТ РАБОТУ. Не прочиталось — берём окружение.
// Обратное поведение опаснее: недоступная на минуту база тихо остановила бы
// весь ИИ, и никто бы не понял, почему.

import AiSettings, {
  ПРОВАЙДЕРЫ,
  НАЗНАЧЕНИЯ,
  ТОЛЬКО_OPENAI,
} from "./aiSettings.model.js";

/* Модели по умолчанию — по одной на назначение и провайдера. Имена живут
   здесь, а не в десяти файлах: когда выходит новая версия, правится одна
   таблица. */
export const МОДЕЛИ_ПО_УМОЛЧАНИЮ = {
  anthropic: {
    translation: "claude-sonnet-5",
    chat: "claude-haiku-4-5-20251001",
    summary: "claude-sonnet-5",
    consultation: "claude-opus-5",
    speech: "", // нет такого API
    image: "", // нет такого API
  },
  openai: {
    translation: "gpt-4o-mini",
    chat: "gpt-4o-mini",
    summary: "gpt-4o-mini",
    consultation: "gpt-4o",
    speech: "whisper-1",
    image: "gpt-image-1",
  },
};

/* Переменные окружения, которыми назначение задавалось до появления
   админки. Они остаются вторым источником: на сервере уже прописаны и
   менять их ради переезда незачем. */
const ENV_МОДЕЛЬ = {
  translation: "TRANSLATION_MODEL",
  chat: "CHAT_TRANSLATION_MODEL",
  summary: "SUMMARY_MODEL",
  consultation: "CONSULTATION_MODEL",
  speech: "STT_MODEL",
  image: "IMAGE_MODEL",
};

const КЭШ_МС = 5000;
let кэш = null;
let кэшОт = 0;

/** Провайдер по умолчанию для всей платформы. */
function провайдерИзОкружения() {
  const из = String(process.env.AI_PROVIDER || "").toLowerCase();
  return ПРОВАЙДЕРЫ.includes(из) ? из : "anthropic";
}

/**
 * Настройки целиком: провайдер по умолчанию и переопределения по частям.
 *
 * @param {{fresh?: boolean}} [опции] fresh — читать мимо кэша (для админки,
 *   которая только что записала и обязана показать записанное).
 */
export async function настройкиИИ({ fresh = false } = {}) {
  if (!fresh && кэш && Date.now() - кэшОт < КЭШ_МС) return кэш;

  let документ = null;
  try {
    документ = await AiSettings.findOne({ key: "ai" }).lean();
  } catch (err) {
    console.error("[ai] не удалось прочитать настройки:", err.message);
  }

  const базовый = документ?.provider || провайдерИзОкружения();
  const задачи = документ?.tasks || {};

  кэш = {
    provider: базовый,
    tasks: Object.fromEntries(
      НАЗНАЧЕНИЯ.map((н) => {
        const своё = задачи[н] || {};
        // У назначения, которого нет у Anthropic, выбор фиктивен: чем бы ни
        // была настройка, работает OpenAI. Честнее сказать это здесь, чем
        // ловить пустой ответ в четырёх местах.
        const провайдер = ТОЛЬКО_OPENAI.includes(н)
          ? "openai"
          : своё.provider || базовый;

        const модель =
          своё.model ||
          process.env[ENV_МОДЕЛЬ[н]] ||
          МОДЕЛИ_ПО_УМОЛЧАНИЮ[провайдер]?.[н] ||
          "";

        return [н, { provider: провайдер, model: модель, fixed: ТОЛЬКО_OPENAI.includes(н) }];
      }),
    ),
    updatedAt: документ?.updatedAt || null,
    lastChange: документ?.lastChange || "",
  };
  кэшОт = Date.now();
  return кэш;
}

/**
 * Кто и чем выполняет эту задачу.
 *
 * @param {string} назначение из НАЗНАЧЕНИЯ
 * @returns {Promise<{provider: string, model: string, fixed: boolean}>}
 */
export async function провайдерДля(назначение) {
  const все = await настройкиИИ();
  return (
    все.tasks[назначение] || {
      provider: все.provider,
      model: МОДЕЛИ_ПО_УМОЛЧАНИЮ[все.provider]?.[назначение] || "",
      fixed: false,
    }
  );
}

/** Сбросить кэш — зовётся сразу после записи из админки. */
export function сброситьКэшИИ() {
  кэш = null;
  кэшОт = 0;
}

/**
 * Записать настройки.
 *
 * Отдельные назначения меняются по одному: правка перевода не должна
 * трогать консультации, которые кто-то настроил месяц назад.
 */
export async function сохранитьНастройкиИИ({ adminId, provider, tasks = {} }) {
  const обновление = { updatedBy: adminId || null };

  if (provider) {
    if (!ПРОВАЙДЕРЫ.includes(provider)) {
      throw new Error("Неизвестный провайдер ИИ: " + provider);
    }
    обновление.provider = provider;
    обновление.lastChange = `Провайдер по умолчанию: ${provider}`;
  }

  for (const [назначение, значение] of Object.entries(tasks)) {
    if (!НАЗНАЧЕНИЯ.includes(назначение)) continue;
    if (ТОЛЬКО_OPENAI.includes(назначение) && значение?.provider === "anthropic") {
      throw new Error(
        `Задача «${назначение}» у Anthropic не выполняется — такого API нет`,
      );
    }
    обновление[`tasks.${назначение}`] = {
      provider: значение?.provider || null,
      model: значение?.model || "",
    };
    обновление.lastChange = `Настроено назначение: ${назначение}`;
  }

  await AiSettings.updateOne(
    { key: "ai" },
    { $set: обновление, $setOnInsert: { key: "ai" } },
    { upsert: true },
  );

  сброситьКэшИИ();
  return настройкиИИ({ fresh: true });
}

export { ПРОВАЙДЕРЫ, НАЗНАЧЕНИЯ, ТОЛЬКО_OPENAI };

export default {
  настройкиИИ,
  провайдерДля,
  сохранитьНастройкиИИ,
  сброситьКэшИИ,
};
