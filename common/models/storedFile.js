// server/common/models/storedFile.js
// ─────────────────────────────────────────────────────────────────────
//   Реестр загруженных файлов: одна запись на каждый файл, попавший в
//   хранилище.
//
//   ЗАЧЕМ ОТДЕЛЬНЫЙ РЕЕСТР, А НЕ ПОДСЧЁТ ПО МЕСТУ. Файлы лежат двумя
//   способами: встроенным массивом в документе исследования (18 типов в
//   myClinic — рентген, КТ, МРТ, холтер и прочие) и отдельной коллекцией
//   File у клиник. Посчитать «сколько файлов у этого врача» пришлось бы
//   обходом восемнадцати коллекций на каждую загрузку.
//
//   Реестр даёт одну точку счёта и, что важнее, РАЗМЕР. Сегодня тариф
//   считает штуки, но расход на хранение измеряется байтами: сто снимков
//   КТ дороже тысячи PDF. Поле size позволит перейти на гигабайты, не
//   перестраивая учёт.
//
//   ВЛАДЕЛЕЦ — ТОТ, КТО ЗАГРУЗИЛ, а не тот, о ком документ. Файлы в
//   архив кладёт врач; пациент не загружает ничего (записи вносит врач, у
//   которого он наблюдается). Ограничивать пациента за то, чего он не
//   делает, значило бы блокировать врача посреди приёма из-за чужой
//   подписки.
//
//   ЗАПИСЬ НЕ УДАЛЯЕТСЯ ВМЕСТЕ С ФАЙЛОМ автоматически: реестр знает, что
//   лежит в R2, и нужен уборщику-сироте (jobs/r2OrphanCleanup.cron.js).
//   Освобождение места — отдельная операция, см. releaseStoredFile.
// ─────────────────────────────────────────────────────────────────────

import mongoose from "mongoose";

const storedFileSchema = new mongoose.Schema(
  {
    // Кто загрузил — с него и считается квота.
    ownerId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
      index: true,
    },

    url: { type: String, required: true, index: true },
    fileName: { type: String, default: "", trim: true, maxlength: 300 },
    mime: { type: String, default: "", trim: true, maxlength: 120 },
    size: { type: Number, default: 0 }, // байты

    // Зачем загружали: исследование, аватар, логотип клиники, картинка к
    // статье. Нужно, чтобы понимать структуру расхода и чтобы однажды
    // можно было исключить из квоты то, что к архиву отношения не имеет.
    context: { type: String, default: "other", trim: true, maxlength: 60 },

    // Файл удалён из хранилища — место освобождено.
    releasedAt: { type: Date, default: null },
  },
  { timestamps: true, collection: "stored_files" },
);

// Основной запрос — «сколько занимает этот владелец»: только живые.
storedFileSchema.index({ ownerId: 1, releasedAt: 1 });

const StoredFile =
  mongoose.models.StoredFile ||
  mongoose.model("StoredFile", storedFileSchema, "stored_files");

export default StoredFile;
