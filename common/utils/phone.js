// common/utils/phone.js
//
// Проверка телефона на входе. Отдельно от normalizePhone из crypto.js —
// и это разделение принципиально.
//
// normalizePhone ПРИВОДИТ строку к каноническому виду, и от неё считается
// слепой индекс (sha256), по которому пациента потом находят. Она обязана
// оставаться стабильной: сделай её строже — и записи, заведённые раньше с
// обрезанным номером, перестанут находиться поиском и проверкой дублей,
// потому что их хеш посчитан от прежнего значения. Историю чинят миграцией,
// а не ужесточением нормализатора.
//
// Здесь же — ворота для НОВЫХ данных. Прежняя проверка на стороне клиента
// («плюс и до 15 цифр») пропускала недобранный номер: маска оставляла в
// строке подчёркивания, они не цифры и просто отбрасывались, так что
// «+994 50 ___ __» уезжало в карточку как «+99450». Клиент это уже не
// присылает, но сервер обязан отказывать сам: у него есть и другие
// источники — мобильное приложение, прямой вызов API, старая вкладка.

import { parsePhoneNumberFromString } from "libphonenumber-js";

/**
 * Настоящий ли это номер.
 *
 * Пустая строка — валидна: телефон в анкетах необязателен, и отсутствие
 * номера не должно отличаться от «поле не заполняли».
 *
 * @param {string} raw номер в любом виде, с разделителями или без
 * @returns {boolean}
 */
export function isValidPhoneInput(raw) {
  const value = String(raw ?? "").trim();
  if (!value) return true;

  const digits = value.replace(/\D/g, "");
  if (!digits) return false;

  const parsed = parsePhoneNumberFromString(`+${digits}`);
  return Boolean(parsed && parsed.isValid());
}

/** Единый текст отказа — чтобы во всех анкетах он звучал одинаково. */
export const INVALID_PHONE_MESSAGE =
  "Неверный номер телефона: проверьте код страны и количество цифр.";

export default { isValidPhoneInput, INVALID_PHONE_MESSAGE };
