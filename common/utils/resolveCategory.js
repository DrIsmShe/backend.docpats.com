//
// Рубрика статьи приходит с фронта то идентификатором, то названием.
//
// ПОЧЕМУ ТАК ВЫШЛО. Список статей отдаёт рубрику уже переведённой — это
// нужно, чтобы карточка показывала «ЛОР-болезни», а не сырой ObjectId.
// Ссылка «править» несла в форму то же самое значение, и форма отправляла
// на сервер НАЗВАНИЕ. Схема ждёт ObjectId, Mongoose бросал CastError,
// контроллер ловил его и отвечал 500 — статья не сохранялась, а человек
// видел «ошибка сервера» и не понимал, что именно не так.
//
// Фронт исправлен и шлёт идентификатор. Этот резолвер — вторая линия: у
// части людей в браузере ещё лежит старая сборка, и ронять их правку
// из-за кэша нельзя.
//
// ЧЕГО ЗДЕСЬ НЕТ. Создания рубрики «на лету»: неизвестное название — это
// ошибка ввода, а не заявка на новую рубрику. Отвечаем понятным 400.

import mongoose from "mongoose";
import Category from "../models/Articles/articlesCategories.js";

const ЭТО_ID = (v) => /^[a-f0-9]{24}$/i.test(String(v || ""));

/**
 * Приводит значение рубрики к ObjectId.
 *
 * @returns {{ ok: true, value: mongoose.Types.ObjectId | null }
 *          | { ok: false, message: string }}
 *   `value: null` — рубрику не выбрали; это допустимо, поле необязательное.
 */
export async function разобратьРубрику(значение) {
  // Пусто — рубрику не выбрали. Пустая строка до схемы доходить не должна:
  // "" в поле ObjectId — тот же CastError, что и название.
  if (значение === undefined || значение === null || значение === "") {
    return { ok: true, value: null };
  }

  // Объект после populate: {_id, name, ...}.
  const сырое =
    typeof значение === "object" && значение !== null
      ? значение._id || значение.id
      : значение;

  if (ЭТО_ID(сырое)) {
    return { ok: true, value: new mongoose.Types.ObjectId(String(сырое)) };
  }

  const имя = String(сырое).trim();
  if (!имя) return { ok: true, value: null };

  // Ищем по исходному имени и по любому из пяти переводов: с фронта
  // приходит то, что человек видел на экране, а видел он перевод.
  const найдена = await Category.findOne({
    $or: [
      { name: имя },
      { "title.ru": имя },
      { "title.en": имя },
      { "title.az": имя },
      { "title.tr": имя },
      { "title.ar": имя },
    ],
  })
    .select("_id")
    .lean();

  if (!найдена) {
    return { ok: false, message: `Рубрика «${имя}» не найдена` };
  }
  return { ok: true, value: найдена._id };
}

export default разобратьРубрику;
