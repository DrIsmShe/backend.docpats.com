// Работа с медиафайлом через ffmpeg.
//
// Бинарник есть не везде: на сервере он лежит в bin/ (там нет sudo), на
// машине разработчика может отсутствовать вовсе. Проверяем то, что должно
// быть верно в обоих случаях — и в первую очередь, что ОТСУТСТВИЕ
// инструмента не роняет ничего: распознавание в таком случае идёт прежним
// путём, а не отключается.

import { describe, it, expect } from "vitest";
import fs from "node:fs/promises";

import {
  ffmpegДоступен,
  временныйФайл,
  длительность,
  естьЗвук,
} from "../../modules/video/media/ffmpeg.js";

describe("временный файл", () => {
  it("создаётся в своём каталоге и убирается целиком", async () => {
    const ф = await временныйФайл(".mp3");
    await fs.writeFile(ф.путь, "проба");

    expect(await fs.readFile(ф.путь, "utf8")).toBe("проба");

    await ф.убрать();
    await expect(fs.access(ф.путь)).rejects.toThrow();
  });

  it("повторная уборка не бросает", async () => {
    const ф = await временныйФайл(".mp4");
    await ф.убрать();
    // Второй раз — уже нечего убирать, и это не ошибка: уборка стоит в
    // finally и выполняется на любом пути.
    await expect(ф.убрать()).resolves.not.toThrow();
  });
});

describe("наличие ffmpeg", () => {
  it("отвечает да или нет, но не бросает", async () => {
    const есть = await ffmpegДоступен();
    expect(typeof есть).toBe("boolean");
  });

  it("ответ не меняется между вызовами", async () => {
    // Проверка кеша: спрашивать систему на каждый ролик незачем.
    expect(await ffmpegДоступен()).toBe(await ffmpegДоступен());
  });
});

describe("разбор файла без ffmpeg", () => {
  it("длительность несуществующего файла не роняет процесс", async () => {
    // Когда бинарника нет, spawn бросает ENOENT; когда есть — ffprobe
    // ругается на отсутствующий файл. Оба случая должны прийти ошибкой,
    // а не падением воркера.
    await expect(длительность("нет-такого-файла.mp4")).rejects.toThrow();
  });

  it("вопрос о звуке в сомнительном случае отвечает «есть»", async () => {
    // Догадка не должна отменять распознавание: пусть решает
    // распознаватель, а не наша неудачная проверка.
    expect(await естьЗвук("нет-такого-файла.mp4")).toBe(true);
  });
});
