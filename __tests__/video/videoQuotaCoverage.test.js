// У каждого тарифа должны быть заданы квоты видео.
//
// ЗАЧЕМ ЭТА ПРОВЕРКА. Отсутствующее значение трактуется как «без
// ограничений»: забытый тариф молча получает безлимитное хранилище, и
// узнать об этом можно только по счёту Cloudflare. Девять платных тарифов
// из тринадцати именно так и жили.
//
// Проверка ловит не «правильные» числа — их выбирает человек, — а сам
// пропуск: новый тариф не должен появиться без решения о видео.

import { describe, it, expect } from "vitest";
import { PLAN_LIMITS } from "../../common/config/aiPlanLimits.js";

/** Гость — не тариф: у него всё по нулям, и это осознанно. */
const ТАРИФЫ = Object.entries(PLAN_LIMITS);

describe("квоты видео заданы для всех тарифов", () => {
  it("тарифов вообще больше одного", () => {
    // Защита от бессмысленно зелёной проверки на пустом списке.
    expect(ТАРИФЫ.length).toBeGreaterThan(5);
  });

  for (const [имя, лимиты] of ТАРИФЫ) {
    it(`${имя}: хранилище задано явно`, () => {
      expect(
        лимиты.videraStorageGb,
        `у тарифа ${имя} нет videraStorageGb — это молчаливый безлимит`,
      ).toBeTypeOf("number");
    });

    it(`${имя}: минуты сборки заданы явно`, () => {
      expect(
        лимиты.videraRenderMinutes,
        `у тарифа ${имя} нет videraRenderMinutes — это молчаливый безлимит`,
      ).toBeTypeOf("number");
    });
  }

  it("платный тариф не даёт безлимитного хранилища", () => {
    // -1 означает «без ограничений». Для хранилища это прямой путь к
    // счёту, который никто не согласовывал: гигабайты платные всегда.
    const безлимитные = ТАРИФЫ.filter(([, л]) => л.videraStorageGb === -1).map(
      ([имя]) => имя,
    );
    expect(безлимитные).toEqual([]);
  });

  it("бесплатные тарифы скромнее платных", () => {
    // Не про конкретные числа, а про порядок: бесплатный уровень не может
    // давать больше места, чем самый дорогой врачебный.
    expect(PLAN_LIMITS.doctor_free.videraStorageGb).toBeLessThan(
      PLAN_LIMITS.doctor_pro.videraStorageGb,
    );
    expect(PLAN_LIMITS.patient_free.videraStorageGb).toBeLessThan(
      PLAN_LIMITS.patient_std.videraStorageGb,
    );
  });
});
